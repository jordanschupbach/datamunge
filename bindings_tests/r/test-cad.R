test_that("CAD scene owns geometry and preserves mesh exports", {
  solid <- CadSolid_box(2, 3, 4)
  expect_true(solid$valid())
  expect_equal(solid$volume(), 24, tolerance=1e-9)
  moved <- solid$translated(0.5, 0.5, 0.5)
  expect_equal(solid$intersected(moved)$volume(), 13.125, tolerance=1e-6)
  view <- CadScene()
  id <- view$add(solid, "#4080d9", "block")
  rm(solid, moved)
  gc()
  expect_equal(view$object_count(), 1L)
  expect_equal(view$triangle_count(), 12L)
  view$size(96L, 72L)
  view$samples(2L)
  image <- tempfile(fileext=".png")
  view$render(image)
  expect_equal(readBin(image, "raw", 8), as.raw(c(137,80,78,71,13,10,26,10)))
  expect_equal(view$pick_object(48, 36), id)
  export <- tempfile(fileext=".gltf")
  view$save_gltf(export)
  restored <- CadScene_from_file(export)
  expect_equal(restored$object_count(), 1L)
  expect_equal(restored$triangle_count(), 12L)
  expect_error(CadSolid_box(0, 1, 1), "positive")
  expect_error(view$samples(5L))
  expect_error(view$set_joint("absent", 1), "URDF")
})

test_that("URDF views expose independent joints with limit validation", {
  path <- tempfile(fileext=".urdf")
  writeLines('<robot><link name="base"/><link name="tip"><visual><geometry><box size="1 1 1"/></geometry></visual></link><joint name="turn" type="revolute"><parent link="base"/><child link="tip"/><axis xyz="0 0 1"/><limit lower="-2" upper="2"/></joint></robot>', path)
  view <- CadScene_from_urdf(path)
  expect_equal(as.character(view$joint_names()), "turn")
  view$set_joint("turn", 0.5)
  expect_equal(view$object_count(), 1L)
  expect_error(view$set_joint("turn", 3), "limits")
})
