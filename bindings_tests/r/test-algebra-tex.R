test_that("algebra TeX methods return owned strings with native grouping", {
  x <- Expr_variable("x")
  expression <- x$negate()$power(Expr_constant(2))
  source <- expression$to_tex()
  rm(expression, x)
  gc()
  expect_identical(source, "\\left(-x\\right)^{2}")
  expect_identical(Expr_variable("rate_1")$to_tex(), "\\text{rate\\_1}")
  expect_error(Expr_constant(1)$to_tex(0L), "precision")
  p <- Polynomial(c(-1, 0, 1))
  expect_identical(p$to_tex("h"), "{h}^{2} - 1")
  expect_identical(Polynomial(1.23456789)$to_tex("x", 10L), "1.23456789")
  fraction <- RationalFunction(Polynomial(c(1, 1)), Polynomial(c(-1, 1)))
  expect_identical(fraction$to_tex(), "\\frac{x + 1}{x - 1}")
  expect_error(p$to_tex(""), "variable")
})

test_that("calculus uses the native integral and shifted Taylor polynomial", {
  x <- Expr_variable("x")
  expect_equal(definite_integral(x$power(Expr_constant(2)), "x", 0, 3), 9, tolerance = 1e-10)
  taylor <- taylor_series(x$exp(), "x", 1, 4L)
  expect_equal(taylor$evaluate(0), exp(1), tolerance = 1e-12)
  expect_match(taylor$to_tex("h"), "{h}^{4}", fixed = TRUE)
  expect_error(taylor_series(x, "x", 0, -1L), "nonnegative")
})

test_that("native normal draws are reproducible without masking stats rnorm", {
  expect_identical(rnorm, stats::rnorm)
  set_seed(42L)
  first <- as.numeric(native_rnorm(0, 1, 8L))
  set_seed(42L)
  second <- as.numeric(native_rnorm(0, 1, 8L))
  expect_equal(first, second, tolerance = 0)
  expect_length(first, 8L)
})
