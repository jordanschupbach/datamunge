# Native color constructors and exception translation, across the R6 boundary.
test_that("RGB constructors retain numeric calls and parse color strings", {
  color <- RGB$new("#ff448855")
  expect_equal(color$r, 255L)
  expect_equal(color$g, 68L)
  expect_equal(color$b, 136L)
  expect_equal(color$alpha, 85 / 255)
  expect_equal(RGB$new("GrEeN")$g, 128L)
  expect_equal(RGB$new(10L, 20L, 30L)$alpha, 1)
  expect_equal(RGB$new(10L, 20L, 30L, 0.25)$alpha, 0.25)
  plot <- RPlot$create()$lines(c(0, 1), c(1, 2), "fit", color)
  rm(color)
  gc()
  expect_match(plot$to_svg(), "rgb(255,68,136)", fixed = TRUE)
  expect_error(RGB$new("#112233zz"), "color")
})

test_that("axis alias chains retain the plot and reject invalid ranges", {
  plot <- RPlot$create()$xlim(0, 1)$ylim(-4, 4)
  gc()
  expect_equal(plot$x_max(), 1)
  expect_equal(plot$y_min(), -4)
  expect_error(plot$xlim(1, 0))
  expect_error(plot$ylim(0, NaN))
  expect_equal(plot$x_max(), 1)
  expect_equal(plot$y_min(), -4)
})
