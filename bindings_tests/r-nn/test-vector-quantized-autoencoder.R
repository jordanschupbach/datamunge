library(testthat)
nn <- datamungerNN::nn
vq_ids <- function(values,shape) nn$cast(nn$from_vector_int64(values,shape),nn$DType$Int32)

test_that("VQ ties and three independent gradient routes preserve native ownership", {
  e <- nn$from_vector_double(c(-.5,0,.9,.2),c(2L,2L))$requires_grad_()
  b <- nn$from_vector_double(c(-1,0,0,0,1,0),c(3L,2L))$requires_grad_()
  q <- nn$VectorQuantize(e,b,3L,2L)
  expect_equal(q$indices$values(),c(0,2));expect_equal(q$quantized$values(),q$straight_through$values(),tolerance=0)
  expect_equal(q$assignment$dtype(),nn$DType$Float64)
  g <- nn$grad(nn$add(nn$mul(nn$sum(nn$square(q$straight_through)),.5),nn$mul(nn$sum(b),0)),nn$tensor_vector(list(e,b)))
  d <- nn$grad(nn$add(q$codebook_loss,nn$mul(nn$sum(e),0)),nn$tensor_vector(list(e,b)))
  c <- nn$grad(nn$add(nn$mul(q$commitment_loss,.25),nn$mul(nn$sum(b),0)),nn$tensor_vector(list(e,b)))
  expect_equal(g[[1]]$values(),q$quantized$values(),tolerance=0);expect_equal(g[[2]]$values(),rep(0,6))
  expect_equal(d[[1]]$values(),rep(0,4));expect_equal(d[[2]]$values(),c(-.25,0,0,0,.05,-.1),tolerance=1e-14)
  expect_equal(c[[1]]$values(),c(.0625,0,-.0125,.025),tolerance=1e-14);expect_equal(c[[2]]$values(),rep(0,6))
  override <- vq_ids(c(2L,1L),c(1L,2L));changed <- nn$VectorQuantize(e,b,3L,2L,override)
  expect_equal(changed$indices$values(),c(2,1));expect_equal(changed$quantized$values(),nn$VqLookup(override,b,3L)$values(),tolerance=0)
})

test_that("Spatial nested fields survive GC and caller Adam owns the update", {
  t <- nn$DType$Float64;p <- nn$ParameterStore(2707L,t)
  image <- nn$full(c(2L,8L,12L,1L),.3,t)$requires_grad_()
  o <- nn$VectorQuantizedAutoencoder(p,image,3L,2L,3L,.5)
  expect_equal(p$size(),9)
  q <- o$vq;probability <- o$probability;loss <- o$loss;expected <- probability$values();rm(o);gc()
  fields <- c("indices","assignment","quantized","straight_through","codebook_loss","commitment_loss")
  retained <- lapply(fields,function(name)do.call("$",list(q,name)));names(retained) <- fields
  snapshots <- lapply(retained,function(x)x$values());rm(q);gc()
  for(name in fields)expect_equal(retained[[name]]$values(),snapshots[[name]],tolerance=0)
  ids <- retained$indices$reshape(c(2L,6L))
  expect_equal(nn$sigmoid(nn$VqDecoder(p,nn$VqLookup(ids,p$at("codebook"),3L),8L,12L,2L,3L))$values(),expected,tolerance=0)
  derivatives <- nn$grad(loss,nn$tensor_vector(c(nn$tensor_list(p$parameters()),list(image))))
  expect_length(derivatives,10);expect_true(all(vapply(derivatives,function(x)all(is.finite(x$values())),logical(1))))
  config <- nn$OptimizerConfig();config$kind <- nn$OptimizerKind$Adam
  optimizer <- nn$Optimizer(p,.003,config);before <- p$flatten();optimizer$step(nn$tensor_vector(derivatives[seq_len(9)]))
  expect_equal(optimizer$iterations(),1);expect_false(identical(p$flatten(),before))
  default <- nn$ParameterStore(2707L);d <- nn$VectorQuantizedAutoencoder(default,nn$full(c(2L,28L,28L,1L),.3))
  expect_equal(default$count(),805);expect_equal(d$encoded$shape(),c(98,4))
  empty <- nn$ParameterStore(1L)
  expect_error(nn$VectorQuantizedAutoencoder(empty,nn$zeros(c(1L,28L,28L,1L)),0L));expect_equal(empty$size(),0)
  expect_error(nn$VqLookup(vq_ids(-1L,c(1L,1L)),d$book))
})

test_that("Raster prior uses copied fitting codes and explicit uniforms", {
  fit <- vq_ids(c(0L,1L,1L,0L),c(2L,2L));prior <- nn$VqMarkovPrior(fit,2L);rm(fit);gc()
  expect_equal(prior$counts()$values(),c(0,1,1,0,1,1))
  expect_equal(prior$probabilities()$values(),c(.25,.75,.75,.25,.5,.5),tolerance=0)
  export <- prior$counts();export$fill_(99);expect_equal(prior$counts()$values(),c(0,1,1,0,1,1))
  u <- nn$from_vector_double(c(.5,.75,.25,.5,.1,.75),c(2L,3L))
  expect_equal(prior$Sample(u)$values(),c(1,1,0,1,0,1))
  expect_equal(prior$Nll(vq_ids(c(0L,1L,1L,0L),c(2L,2L))),-log(.5)-log(.75),tolerance=1e-14)
  bank <- nn$MidpointUniformNoise(c(20L,49L),2729L);expect_equal(prior$Sample(bank)$values(),prior$Sample(bank)$values(),tolerance=0)
  usage <- nn$VqUsage(vq_ids(c(0L,1L,0L,1L),c(2L,2L)),4L)
  counts <- usage$counts;expect_equal(usage$perplexity,2);rm(usage);gc();expect_equal(counts$values(),c(2,2,0,0))
  expect_error(prior$Sample(nn$zeros(c(1L,2L))));expect_error(prior$Sample(nn$full(c(1L,2L),1,nn$DType$Float64)))
  expect_error(nn$VqMarkovPrior(nn$zeros(c(1L,2L),nn$DType$Int32),2L,0))
})
