testthat::test_that("spatial autoencoder endpoints own handles and preserve complete gradients", {
  nn <- datamungerNN::nn
  p <- nn$ParameterStore(1801L)
  image <- nn$full(c(2L,8L,12L,1L), .25)$requires_grad_()
  result <- nn$ConvolutionalAutoencoder(p, image)
  testthat::expect_equal(p$count(), 741)
  testthat::expect_equal(result$code$shape(), c(2L,2L,3L,4L))
  testthat::expect_equal(result$reconstruction$shape(), c(2L,8L,12L,1L))
  decoded <- nn$ConvolutionalDecoder(p, result$code)
  testthat::expect_equal(decoded$reconstruction$values(), result$reconstruction$values())
  testthat::expect_equal(decoded$hidden$values(), result$decoder1$values())
  derivatives <- nn$grad(nn$mse(result$reconstruction, image), c(nn$tensor_list(p$parameters()), list(image)))
  testthat::expect_length(derivatives, 9L)
  testthat::expect_true(all(vapply(derivatives, function(g) all(is.finite(g$values())) && any(g$values()!=0), logical(1))))
  code <- result$code
  reconstruction <- decoded$reconstruction
  expected <- reconstruction$values()
  rm(result, decoded)
  invisible(gc())
  testthat::expect_equal(reconstruction$values(), expected)
  testthat::expect_equal(code$shape(), c(2L,2L,3L,4L))
  empty <- nn$ParameterStore(1L)
  testthat::expect_error(nn$ConvolutionalAutoencoder(empty,nn$zeros(c(1L,5L,4L,1L))), "multiples")
  testthat::expect_error(nn$ConvolutionalDecoder(empty,nn$zeros(c(1L,1L,1L,3L))), "decoder")
  testthat::expect_equal(empty$size(), 0L)
})

testthat::test_that("Gaussian banks are local and corruption owns detached augmentation data", {
  nn <- datamungerNN::nn
  set.seed(123L)
  previous <- .Random.seed
  bank <- nn$GaussianNoise(c(2L,2L),1L,1673L)
  expected <- bank$values()
  nn$GaussianNoise(13L,2L,991L)
  testthat::expect_equal(nn$GaussianNoise(c(2L,2L),1L,1673L)$values(),expected)
  testthat::expect_false(identical(nn$GaussianNoise(c(2L,2L),1L,1674L)$values(),expected))
  testthat::expect_identical(.Random.seed,previous)
  testthat::expect_equal(nn$GaussianNoise(1L,1L,2147483648)$values(),-0.9908843253272774,tolerance=1e-14)
  testthat::expect_equal(nn$GaussianNoise(1L,1L,4294967295)$values(),1.6481125509743353,tolerance=1e-14)
  testthat::expect_error(nn$GaussianNoise(1L,1L,4294967296),"seed")
  testthat::expect_error(nn$GaussianNoise(1L,1L,-1),"seed")
  clean <- nn$from_vector(c(0,.2,.8,1),c(2L,2L))$requires_grad_()
  noise <- nn$from_vector_double(c(-2,1,-1,2),c(1L,2L,2L))$requires_grad_()
  result <- nn$CorruptForDenoising(clean,noise,.3)
  testthat::expect_equal(result$values(),c(0,.5,.5,1),tolerance=6e-8)
  testthat::expect_false(result$requires_grad())
  tiny <- nn$CorruptForDenoising(nn$zeros(c(1L,2L)),
      nn$from_vector_double(c(-1e-308,1e-308),c(1L,1L,2L)),1)$values()
  testthat::expect_identical(1/tiny,c(-Inf,Inf))
  testthat::expect_equal(nn$CorruptForDenoising(clean,noise,0)$values(),clean$values())
  rm(clean,noise)
  invisible(gc())
  testthat::expect_equal(result$values(),c(0,.5,.5,1),tolerance=6e-8)
  testthat::expect_error(nn$CorruptForDenoising(nn$zeros(c(2L,2L)),bank,-1),"sigma")
  testthat::expect_error(nn$GaussianNoise(-1L,1L,12L),"negative")
})
