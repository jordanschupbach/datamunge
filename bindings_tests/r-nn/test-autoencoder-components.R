testthat::test_that("canonical contractive values own nested handles and preserve gradients", {
  nn <- datamungerNN::nn
  p <- nn$ParameterStore(1753L)
  input <- nn$full(c(2L, 3L), .25)
  result <- nn$ContractiveAutoencoder(p, input, .01, 3L, 2L)
  testthat::expect_equal(result$code$shape(), c(2L, 2L))
  testthat::expect_equal(result$reconstruction$shape(), c(2L, 3L))
  testthat::expect_equal(p$count(), 17)
  testthat::expect_equal(result$loss$item(), result$mse$item() + .01 * result$penalty$mean$item(), tolerance=1e-7)
  derivatives <- nn$grad(result$loss, p$parameters())
  testthat::expect_length(derivatives, 4L)
  testthat::expect_true(all(vapply(derivatives, function(g) all(is.finite(g$values())), logical(1))))
  penalty <- result$penalty
  expected <- penalty$per_example$values()
  rm(result)
  invisible(gc())
  testthat::expect_equal(penalty$per_example$values(), expected)
  mean <- penalty$mean
  rm(penalty)
  invisible(gc())
  testthat::expect_true(is.finite(mean$item()))
  weights <- nn$ones(c(3L, 2L))$requires_grad_()
  code <- nn$sigmoid(nn$matmul(nn$zeros(c(4L, 3L)), weights))
  regularizer <- nn$SigmoidEncoderContraction(code, weights)
  testthat::expect_equal(regularizer$mean$item(), .375)
  testthat::expect_equal(nn$grad(regularizer$mean, list(weights))[[1L]]$values(), rep(.125, 6L))
  testthat::expect_error(nn$ContractiveAutoencoder(nn$ParameterStore(1L), input, -1, 3L, 2L), "weight")
})

