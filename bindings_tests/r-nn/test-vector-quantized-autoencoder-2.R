library(testthat)
nn <- datamungerNN::nn
vq2_ids <- function(values,shape) nn$cast(nn$from_vector_int64(values,shape),nn$DType$Int32)

test_that("Two-scale default census and discrete-only decoding agree", {
  p <- nn$ParameterStore(2801L);o <- nn$VectorQuantizedAutoencoder2(p,nn$full(c(2L,28L,28L,1L),.3))
  expect_equal(p$size(),14);expect_equal(p$count(),1157)
  expect_equal(o$encoded_top$shape(),c(98,4));expect_equal(o$encoded_bottom$shape(),c(392,4));expect_equal(o$top_feature$shape(),c(2,14,14,4))
  expect_equal(o$top$quantized$values(),o$top$straight_through$values(),tolerance=0)
  expect_equal(o$bottom$quantized$values(),o$bottom$straight_through$values(),tolerance=0)
  top <- nn$VqLookup(o$top$indices$reshape(c(2L,49L)),o$top_book)
  bottom <- nn$VqLookup(o$bottom$indices$reshape(c(2L,196L)),o$bottom_book)
  expect_equal(nn$sigmoid(nn$Vq2Decoder(p,bottom,nn$Vq2TopDecoder(p,top)))$values(),o$probability$values(),tolerance=0)
})

test_that("Eleven fields and nested records survive GC and caller owns Adam", {
  t <- nn$DType$Float64;p <- nn$ParameterStore(2801L,t);image <- nn$full(c(2L,8L,12L,1L),.3,t)$requires_grad_()
  o <- nn$VectorQuantizedAutoencoder2(p,image,nn$Tensor(),3L,2L,3L,.25)
  names <- c("encoded_top","encoded_bottom","top_book","bottom_book","top_feature","probability","nll","reconstruction_loss","loss")
  fields <- lapply(names,function(name)do.call("$",list(o,name)));names(fields) <- names
  top <- o$top;bottom <- o$bottom;rm(o);gc();top_ids <- top$indices;bottom_ids <- bottom$indices;top_value <- top$quantized;bottom_value <- bottom$quantized;rm(top,bottom);gc()
  expect_equal(top_value$shape(),c(12,2));expect_equal(bottom_value$shape(),c(48,2))
  expect_true(all(vapply(fields,function(a)all(is.finite(a$values())),logical(1))))
  feature <- nn$Vq2TopDecoder(p,nn$VqLookup(top_ids$reshape(c(2L,6L)),fields$top_book,3L),8L,12L,2L)
  decoded <- nn$sigmoid(nn$Vq2Decoder(p,nn$VqLookup(bottom_ids$reshape(c(2L,24L)),fields$bottom_book,3L),feature,3L))
  expect_equal(decoded$values(),fields$probability$values(),tolerance=0)
  derivatives <- nn$grad(fields$loss,nn$tensor_vector(c(nn$tensor_list(p$parameters()),list(image))))
  expect_length(derivatives,15);expect_true(all(vapply(derivatives,function(a)all(is.finite(a$values())),logical(1))))
  config <- nn$OptimizerConfig();config$kind <- nn$OptimizerKind$Adam;adam <- nn$Optimizer(p,.003,config);before <- p$flatten();adam$step(nn$tensor_vector(derivatives[seq_len(14)]))
  expect_equal(adam$iterations(),1);expect_false(identical(before,p$flatten()))
})

test_that("Fine encoding is top-conditioned and reconstruction stops both books", {
  t <- nn$DType$Float64;p <- nn$ParameterStore(2801L,t);image <- nn$full(c(2L,8L,12L,1L),.3,t)
  nn$VectorQuantizedAutoencoder2(p,image,nn$Tensor(),3L,2L,3L,.25)
  p$set("top_codebook",nn$from_vector_double(c(.1,.2,.5,.6,-.2,.3),c(3L,2L)))
  p$set("top_decoder/W",nn$full(p$at("top_decoder/W")$shape(),.1,t));p$set("top_decoder/b",nn$full(2L,.1,t))
  p$set("bottom_projection/W",nn$full(p$at("bottom_projection/W")$shape(),.2,t))
  o <- nn$VectorQuantizedAutoencoder2(p,image,nn$Tensor(),3L,2L,3L,.25)
  expect_true(any(abs(nn$grad(nn$mean(nn$square(o$encoded_bottom)),nn$tensor_vector(list(o$encoded_top)))[[1]]$values())>1e-10))
  o <- nn$VectorQuantizedAutoencoder2(p,image,nn$Tensor(),3L,2L,3L,.25)
  probe <- nn$add(o$reconstruction_loss,nn$mul(nn$add(nn$sum(o$top_book),nn$sum(o$bottom_book)),0))
  books <- nn$grad(probe,nn$tensor_vector(list(o$top_book,o$bottom_book)))
  expect_equal(books[[1]]$values(),rep(0,6));expect_equal(books[[2]]$values(),rep(0,6))
  zero <- nn$VectorQuantizedAutoencoder2(p,image,nn$zeros(c(2L,6L),nn$DType$Int32),3L,2L,3L,.25)
  one <- nn$VectorQuantizedAutoencoder2(p,image,nn$ones(c(2L,6L),nn$DType$Int32),3L,2L,3L,.25)
  expect_false(identical(zero$encoded_bottom$values(),one$encoded_bottom$values()))
  expect_equal(one$top$indices$values(),rep(1,12))
})

test_that("Bad overrides fail before any leaves are created", {
  p <- nn$ParameterStore(2801L);image <- nn$zeros(c(1L,28L,28L,1L))
  for(top in list(nn$zeros(c(1L,49L)),nn$zeros(c(1L,48L),nn$DType$Int32),nn$full(c(1L,49L),16,nn$DType$Int32))) expect_error(nn$VectorQuantizedAutoencoder2(p,image,top))
  expect_equal(p$size(),0)
})

test_that("Conditional raster prior respects aligned parents and explicit CDF", {
  top <- vq2_ids(c(0L,1L),c(1L,2L));bottom <- vq2_ids(c(0L,0L,1L,1L,0L,0L,1L,1L),c(1L,8L))
  prior <- nn$Vq2ConditionalPrior(top,bottom,1L,2L,2L)
  expect_equal(prior$counts()$values(),c(2,0,1,0,1,0,0,2,0,2,0,0))
  expected <- prior$probabilities()$values();export <- prior$probabilities();export$fill_(0);expect_equal(prior$probabilities()$values(),expected,tolerance=0)
  expect_equal(prior$Sample(top,nn$full(c(1L,8L),.2,nn$DType$Float64))$values(),bottom$values(),tolerance=0)
  expect_equal(prior$Nll(top,bottom),-2*log(.75)-6*log(2.5/3),tolerance=1e-14);rm(top,bottom);gc();expect_equal(prior$counts()$shape(),c(2,3,2))
  top <- nn$zeros(c(1L,1L),nn$DType$Int32);bottom <- nn$zeros(c(1L,4L),nn$DType$Int32)
  small <- nn$Vq2ConditionalPrior(top,bottom,1L,1L,2L)
  expect_equal(small$Sample(top,nn$full(c(1L,4L),.75,nn$DType$Float64))$values(),rep(1,4))
  bank <- nn$MidpointUniformNoise(c(1L,4L),2833L);expect_equal(small$Sample(top,bank)$values(),small$Sample(top,bank)$values(),tolerance=0)
  expect_error(small$Sample(top,nn$zeros(c(1L,4L))));expect_error(small$Sample(top,nn$full(c(1L,4L),1,nn$DType$Float64)))
  expect_error(nn$Vq2ConditionalPrior(top,bottom,1L,1L,2L,0))
})
