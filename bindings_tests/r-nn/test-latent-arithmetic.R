library(testthat)
nn <- datamungerNN::nn

test_that("Affine paths preserve extrapolation strides and independent rows", {
  a <- nn$from_vector_double(c(1,2,3,4),c(2L,2L));b <- nn$from_vector_double(c(5,6,7,8),c(2L,2L))
  levels <- nn$from_vector_double(c(0,.5,1,2),4L);path <- nn$LatentLerp(a,b,levels)
  expect_equal(path$shape(),c(2,4,2));expect_true(nn$equal_bits(nn$select(path,1L,0L),a));expect_true(nn$equal_bits(nn$select(path,1L,2L),b))
  expect_equal(path$values()[7],9);strided <- nn$transpose(nn$transpose(a)$contiguous());expect_false(strided$is_contiguous())
  expect_true(nn$equal_bits(nn$LatentLerp(strided,b,levels),path))
  edited <- nn$LatentDirection(a,b,nn$from_vector_double(c(-1,0,2),3L));expect_equal(edited$values()[1],-4)
  expect_true(nn$equal_bits(nn$select(edited,1L,1L),a))
  rows <- nn$LatentFlatten(nn$transpose(path,c(1L,0L,2L)))
  expect_equal(rows$shape(),c(8,2));expect_true(rows$is_contiguous())
  expect_equal(rows$values(),nn$transpose(path,c(1L,0L,2L))$contiguous()$values(),tolerance=0)
  nn$no_grad(function()rows$fill_(7));expect_equal(path$values()[1],1)
})
test_that("All affine inputs retain their native derivatives", {
  t <- nn$DType$Float64;a <- nn$full(c(2L,3L),.4,t)$requires_grad_();b <- nn$full(c(2L,3L),-.7,t)$requires_grad_()
  levels <- nn$from_vector_double(c(-.3,0,.6,1.4),4L)$requires_grad_()
  g <- nn$grad(nn$sum(nn$LatentLerp(a,b,levels)),nn$tensor_vector(list(a,b,levels)))
  expect_equal(g[[1]]$values(),rep(2.3,6),tolerance=1e-14);expect_equal(g[[2]]$values(),rep(1.7,6),tolerance=1e-14);expect_equal(g[[3]]$values(),rep(-6.6,4),tolerance=1e-14)
  g <- nn$grad(nn$sum(nn$LatentDirection(a,b,levels)),nn$tensor_vector(list(a,b,levels)))
  expect_equal(g[[1]]$values(),rep(4,6),tolerance=0);expect_equal(g[[2]]$values(),rep(1.7,6),tolerance=1e-14);expect_equal(g[[3]]$values(),rep(-4.2,4),tolerance=1e-14)
})
test_that("Fitting-label centroids detach and own lifetime", {
  code <- nn$from_vector_double(c(1,-3,2,4,4,9),c(3L,2L))$requires_grad_();labels <- nn$from_vector_int64(c(0,1,0),3L)
  means <- nn$LatentClassMeans(code,labels,2L);expect_equal(means$values(),c(2.5,3,2,4),tolerance=0);expect_false(means$requires_grad())
  expect_true(nn$equal_bits(nn$LatentClassMeans(nn$transpose(nn$transpose(code)$contiguous()),labels,2L),means))
  rm(code,labels);gc();expect_equal(means$values(),c(2.5,3,2,4),tolerance=0)
})
test_that("Native decoder accepts only codes and retains code derivatives", {
  head <- nn$ParameterStore(1471L);full <- nn$UndercompleteAutoencoder(head,nn$full(c(2L,4L),.3),4L,2L)
  before <- head$flatten();prediction <- nn$UndercompleteDecoder(head,full$code,4L,2L)
  expect_true(nn$equal_bits(prediction,full$reconstruction));expect_equal(head$flatten(),before,tolerance=0)
  decoder <- nn$ParameterStore(1471L);code <- nn$full(c(2L,32L),-.3)$requires_grad_();output <- nn$UndercompleteDecoder(decoder,code)
  expect_equal(decoder$size(),2);expect_equal(decoder$count(),25872)
  expect_gt(nn$sum(nn$abs(nn$grad(nn$sum(output),nn$tensor_vector(list(code)))[[1]]))$item(),0)
  rm(head,full,decoder,code);gc();expect_equal(prediction$shape(),c(2,4))
})
test_that("Invalid paths missing classes and invalid decoder inputs fail", {
  a <- nn$ones(c(2L,3L))
  for(levels in list(nn$zeros(0L),nn$ones(2L,nn$DType$Float64),nn$full(2L,NaN)))expect_error(nn$LatentLerp(a,a,levels))
  for(labels in list(nn$zeros(2L),nn$zeros(1L,nn$DType$Int64),nn$zeros(2L,nn$DType$Int64),nn$full(2L,2,nn$DType$Int64)))expect_error(nn$LatentClassMeans(a,labels,2L))
  expect_error(nn$LatentFlatten(a));decoder <- nn$ParameterStore(1471L)
  for(code in list(nn$zeros(c(0L,32L)),nn$zeros(c(2L,31L)),nn$full(c(2L,32L),Inf)))expect_error(nn$UndercompleteDecoder(decoder,code))
  expect_equal(decoder$size(),0)
})
