library(testthat)
nn <- datamungerNN::nn

test_that("Sample rows widen copy strides and retain input gradients", {
  x <- nn$transpose(nn$from_vector_double(0:11,c(2L,3L,2L)),c(1L,0L,2L))$requires_grad_()
  rows <- nn$DoubleSampleRows(x);expect_equal(rows$shape(),c(3,4));expect_equal(rows$dtype(),nn$DType$Float64)
  expect_equal(rows$values(),x$contiguous()$values(),tolerance=0)
  expect_equal(nn$grad(nn$sum(rows),nn$tensor_vector(list(x)))[[1]]$values(),rep(1,12),tolerance=0)
  nn$no_grad(function()rows$fill_(9));expect_equal(x$values()[1],0)
  expect_equal(nn$DoubleSampleRows(nn$ones(3L))$shape(),c(3,1))
})
test_that("SVD PCA freezes fitting state exports independent copies and keeps query paths", {
  fit <- nn$from_vector_double(c(-1,0,0,0,1,0),c(3L,2L))$requires_grad_();pca <- nn$SvdPca(fit,1L)
  expect_equal(pca$mean()$values(),c(0,0),tolerance=0);expect_equal(pca$variances()$item(),1,tolerance=1e-14)
  expect_false(pca$scores()$requires_grad());expect_false(pca$components()$requires_grad())
  query <- nn$from_vector_double(c(2,3),c(1L,2L))$requires_grad_();score <- pca$Transform(query)
  expect_equal(pca$Reconstruct(score)$values(),c(2,0),tolerance=1e-14)
  expect_gt(nn$sum(nn$abs(nn$grad(nn$sum(nn$square(score)),nn$tensor_vector(list(query)))[[1]]))$item(),0)
  before <- pca$Transform(query)$values();pca$mean()$fill_(9);pca$components()$fill_(9);pca$variances()$fill_(9);pca$scores()$fill_(9)
  nn$no_grad(function()fit$fill_(9));expect_equal(pca$Transform(query)$values(),before,tolerance=0)
  kept <- pca$components();rm(pca,fit);gc();expect_equal(kept$shape(),c(2,1))
})
test_that("Prefix inverse constant data and sample variance have the original semantics", {
  pca <- nn$SvdPca(nn$from_vector_double(c(-3,-1,-3,1,3,-1,3,1),c(4L,2L)),2L)
  expect_equal(pca$variances()$values(),c(12,4/3),tolerance=1e-12)
  score <- pca$Transform(nn$from_vector_double(c(2,.5),c(1L,2L)))
  expect_equal(pca$Reconstruct(nn$slice(score,c(0L,0L),c(1L,1L)))$values(),c(2,0),tolerance=1e-13)
  constant <- nn$SvdPca(nn$full(c(3L,4L),7),3L);expect_equal(constant$variances()$values(),rep(0,3),tolerance=0)
  expect_equal(constant$Reconstruct(constant$scores())$values(),rep(7,12),tolerance=0)
})
test_that("Neighbor distance ties membership and first-neighbor labels are deterministic", {
  fit <- nn$from_vector_double(c(-1,0,1,0,0,2,4,0),c(4L,2L));query <- nn$zeros(c(1L,2L))$requires_grad_()
  rows <- nn$NearestFitRows(fit,query,4L);expect_equal(rows$values(),0:3,tolerance=0);expect_equal(rows$dtype(),nn$DType$Int32);expect_false(rows$requires_grad())
  expect_true(nn$equal_bits(rows,nn$NearestFitRows(fit$reshape(c(4L,1L,2L,1L)),query$reshape(c(1L,2L,1L)),4L)))
  a <- nn$from_vector_int64(c(0,1,1,1),c(2L,2L));b <- nn$from_vector_int64(c(1,2,1,1),c(2L,2L));expect_equal(nn$NeighborOverlap(a,b),.75,tolerance=0)
  first <- nn$from_vector_int64(c(0,1,1,0),c(2L,2L));labels <- nn$from_vector_int64(c(4,8),2L)
  expect_equal(nn$NeighborLabelAccuracy(first,labels,nn$from_vector_int64(c(4,9),2L)),.5,tolerance=0)
  rm(fit,query);gc();expect_equal(rows$values(),0:3,tolerance=0)
})
test_that("Malformed tensors retained counts neighbor indices and labels fail", {
  for(bad in list(nn$zeros(c(0L,2L)),nn$ones(c(3L,2L),nn$DType$Int32),nn$full(c(3L,2L),NaN)))expect_error(nn$DoubleSampleRows(bad))
  expect_error(nn$SvdPca(nn$ones(c(1L,3L)),1L));expect_error(nn$SvdPca(nn$ones(c(3L,2L)),0L));expect_error(nn$SvdPca(nn$ones(c(2L,3L)),3L))
  pca <- nn$SvdPca(nn$ones(c(3L,2L)),1L);expect_error(pca$Transform(nn$ones(c(2L,3L))));expect_error(pca$Reconstruct(nn$ones(c(2L,2L))))
  expect_error(nn$NearestFitRows(nn$ones(c(2L,3L)),nn$ones(c(1L,3L)),3L));expect_error(nn$NeighborOverlap(nn$ones(c(2L,2L)),nn$ones(c(2L,2L))))
  expect_error(nn$NeighborLabelAccuracy(nn$full(c(2L,2L),2,nn$DType$Int32),nn$zeros(2L,nn$DType$Int64),nn$zeros(2L,nn$DType$Int64)))
})
