testthat::test_that("native known-factor lattice has owning named splits", {
    nn <- datamungerNN::nn;data <- nn$KnownFactorLattice()
    testthat::expect_length(data,9L);all_ids <- numeric()
    for(split in c("fit","validation","test")){
        count <- if(split=="fit") 210L else 42L
        images <- data[[paste0(split,"_images")]];ids <- data[[paste0(split,"_source_ids")]]
        testthat::expect_equal(images$shape(),c(count,28L,28L,1L))
        testthat::expect_equal(images$dtype(),nn$DType$Float32)
        testthat::expect_false(images$requires_grad())
        testthat::expect_equal(ids$dtype(),nn$DType$Int32)
        testthat::expect_equal(ids$values(),sort(ids$values()))
        testthat::expect_length(intersect(all_ids,ids$values()),0L)
        all_ids <- c(all_ids,ids$values())
    }
    image <- data$test_images;expected <- image$values();rm(data);invisible(gc())
    testthat::expect_equal(image$values(),expected);testthat::expect_equal(length(unique(all_ids)),294L)
})
testthat::test_that("AAE fields own lifetimes and reconstruction ignores prior samples", {
    nn <- datamungerNN::nn;e <- nn$ParameterStore(3501L);g <- nn$ParameterStore(3511L);d <- nn$ParameterStore(3527L)
    x <- nn$full(c(2L,3L),.3);prior <- nn$from_vector(c(-.5,.4,.8,-.2,.1,.6),c(3L,2L))
    out <- nn$AdversarialAutoencoder(e,g,d,x,prior,3L,2L,2L)
    testthat::expect_equal(e$count()+g$count()+d$count(),38)
    testthat::expect_equal(out$prior_logit$shape(),c(3L,1L))
    probability <- out$probability;code <- out$code;loss <- out$reconstruction_loss;expected <- probability$values()
    rm(out);invisible(gc());changed <- nn$AdversarialAutoencoder(e,g,d,x,nn$full(c(4L,2L),2),3L,2L,2L)
    testthat::expect_equal(changed$probability$values(),expected)
    testthat::expect_equal(changed$code$values(),code$values())
    testthat::expect_equal(nn$sigmoid(nn$AaeDecode(g,code,3L,2L,2L))$values(),expected)
    parameters <- lapply(e$names(),function(name)e$at(name));parameters <- c(parameters,lapply(g$names(),function(name)g$at(name)))
    gradients <- nn$grad(loss,parameters)
    testthat::expect_length(gradients,8L)
    testthat::expect_true(all(vapply(gradients,function(a)all(is.finite(a$values())),logical(1))))
})
testthat::test_that("host-owned AAE phases isolate three groups and four Adam states", {
    nn <- datamungerNN::nn;e <- nn$ParameterStore(3501L);g <- nn$ParameterStore(3511L);d <- nn$ParameterStore(3527L)
    x <- nn$full(c(2L,3L),.3);prior <- nn$from_vector(c(-.5,.4,.8,-.2),c(2L,2L))
    nn$AdversarialAutoencoder(e,g,d,x,prior,3L,2L,2L)
    cfg <- nn$OptimizerConfig();cfg$kind <- nn$OptimizerKind$Adam
    optimizers <- lapply(list(e,g,d,e),function(p)nn$Optimizer(p,.003,cfg))
    snapshot <- function()lapply(list(e,g,d),function(p)p$flatten())
    before <- snapshot();out <- nn$AdversarialAutoencoder(e,g,d,x,prior,3L,2L,2L)
    params <- lapply(e$names(),function(name)e$at(name));params <- c(params,lapply(g$names(),function(name)g$at(name)))
    gradients <- nn$grad(out$reconstruction_loss,params)
    optimizers[[1L]]$step(nn$tensor_vector(gradients[1L:4L]));optimizers[[2L]]$step(nn$tensor_vector(gradients[5L:8L]))
    after <- snapshot();testthat::expect_false(identical(before[[1L]],after[[1L]]));testthat::expect_false(identical(before[[2L]],after[[2L]]));testthat::expect_equal(before[[3L]],after[[3L]])
    before <- after;optimizers[[3L]]$minimize(nn$AdversarialAutoencoder(e,g,d,x,prior,3L,2L,2L)$discriminator_loss)
    after <- snapshot();testthat::expect_equal(before[[1L]],after[[1L]]);testthat::expect_equal(before[[2L]],after[[2L]]);testthat::expect_false(identical(before[[3L]],after[[3L]]))
    before <- after;optimizers[[4L]]$minimize(nn$AdversarialAutoencoder(e,g,d,x,prior,3L,2L,2L)$adversarial_loss)
    after <- snapshot();testthat::expect_false(identical(before[[1L]],after[[1L]]));testthat::expect_equal(before[2L:3L],after[2L:3L])
    testthat::expect_equal(vapply(optimizers,function(o)o$iterations(),numeric(1)),rep(1,4))
})
testthat::test_that("Bernoulli NLL is summed and invalid AAE inputs create no leaves", {
    nn <- datamungerNN::nn
    logits <- nn$from_vector_double(c(1000,1000,0,-1000,-1000,0),c(2L,3L))$requires_grad_()
    target <- nn$from_vector_double(c(0,1,.5,1,0,.5),c(2L,3L))$requires_grad_()
    values <- nn$BernoulliPixelNll(logits,target)
    testthat::expect_equal(values$values(),rep(1000+log(2),2L),tolerance=1e-12)
    testthat::expect_equal(nn$grad(nn$sum(values),list(logits,target))[[1L]]$values(),c(1,0,0,-1,0,0))
    e <- nn$ParameterStore(1L);g <- nn$ParameterStore(2L);d <- nn$ParameterStore(3L)
    testthat::expect_error(nn$AdversarialAutoencoder(e,g,d,nn$full(c(1L,3L),-1),nn$zeros(c(1L,2L)),3L,2L,2L),"unit-range")
    testthat::expect_error(nn$AdversarialAutoencoder(e,e,d,nn$zeros(c(1L,3L)),nn$zeros(c(1L,2L)),3L,2L,2L),"distinct")
    testthat::expect_equal(e$size()+g$size()+d$size(),0L)
})
