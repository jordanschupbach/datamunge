library(testthat)
nn <- datamungerNN::nn

test_that("Population scaling detaches and owns fields through GC", {
  code <- nn$from_vector_double(c(1,5,2,5,4,5),c(3L,2L))$requires_grad_()
  fit <- nn$FitTransferScaling(nn$transpose(nn$transpose(code)$contiguous()))
  center <- fit$center;scale <- fit$scale;rm(fit,code);gc()
  expect_equal(center$values(),c(7/3,5),tolerance=0)
  expect_equal(scale$values(),c(sqrt(14/9),1e-6),tolerance=0)
  expect_false(center$requires_grad());expect_false(scale$requires_grad())
  expect_equal(nn$FitTransferScaling(nn$ones(c(1L,2L)),.25)$scale$values(),c(.25,.25),tolerance=0)
})
test_that("Frozen feature paths stop encoder derivatives and retain image derivatives", {
  t <- nn$DType$Float64;x <- nn$full(c(2L,3L),.4,t)$requires_grad_()
  w <- nn$full(c(3L,2L),.5,t)$requires_grad_();b <- nn$full(2L,.2,t)$requires_grad_()
  out <- nn$FrozenEncoderFeatures(x,w,b)
  objective <- nn$add(nn$sum(out),nn$mul(nn$add(nn$sum(w),nn$sum(b)),0))
  g <- nn$grad(objective,nn$tensor_vector(list(x,w,b)))
  expect_equal(g[[1]]$values(),rep(1,6),tolerance=0)
  expect_equal(g[[2]]$values(),rep(0,6),tolerance=0)
  expect_equal(g[[3]]$values(),rep(0,2),tolerance=0)
})
test_that("Classifier copies state exports independent tensors and updates only its head", {
  w <- nn$ones(c(3L,2L));b <- nn$zeros(2L);center <- nn$zeros(2L);scale <- nn$ones(2L)
  model <- nn$FrozenEncoderClassifier(w,b,center,scale,2L);head <- nn$ParameterStore(4703L)
  x <- nn$full(c(2L,3L),.3)$requires_grad_();labels <- nn$cast(nn$from_vector_int64(c(0,1),2L),nn$DType$Int32)
  out <- model$Forward(head,x,labels);before <- out$logits$values()
  w$fill_(9);b$fill_(9);center$fill_(9);scale$fill_(9);model$encoder_weight()$fill_(42)
  expect_equal(model$Forward(head,x)$logits$values(),before,tolerance=0)
  expect_false(model$Forward(head,x)$loss$defined());expect_equal(head$size(),2);expect_equal(head$count(),6)
  expect_gt(nn$sum(nn$abs(nn$grad(out$loss,nn$tensor_vector(list(x)))[[1]]))$item(),0)
  original <- head$flatten();config <- nn$OptimizerConfig();config$kind <- nn$OptimizerKind$Adam
  optimizer <- nn$Optimizer(head,.003,config)
  optimizer$step(nn$tensor_vector(nn$grad(model$Forward(head,x,labels)$loss,head$parameters())))
  expect_false(identical(head$flatten(),original));expect_equal(model$encoder_weight()$values(),rep(1,6),tolerance=0)
  kept <- model$Forward(head,x)$probability;rm(model,out,x,w,b,center,scale);gc()
  expect_equal(kept$shape(),c(2,2));expect_true(all(kept$values()>=0 & kept$values()<=1))
})
test_that("Invalid labels fail before head creation and original census is preserved", {
  model <- nn$FrozenEncoderClassifier(nn$ones(c(784L,32L)),nn$zeros(32L),nn$zeros(32L),nn$ones(32L));head <- nn$ParameterStore(4703L)
  for(labels in list(nn$zeros(2L),nn$zeros(1L,nn$DType$Int32),nn$full(2L,10,nn$DType$Int32)))
    expect_error(model$Forward(head,nn$ones(c(2L,784L)),labels))
  expect_equal(head$size(),0);model$Forward(head,nn$ones(c(2L,784L)));expect_equal(head$count(),330);expect_equal(head$size(),2)
  for(floor in c(0,-1,NaN,Inf,1e100,1e-100))expect_error(nn$FitTransferScaling(nn$ones(c(2L,2L)),floor))
  expect_error(nn$FrozenEncoderClassifier(nn$ones(c(3L,2L)),nn$zeros(2L),nn$zeros(2L),nn$zeros(2L)))
})
