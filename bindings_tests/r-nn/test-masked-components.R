testthat::test_that("native patch inversion and unsigned selections work from R", {
    nn <- datamungerNN::nn
    x <- nn$from_vector(as.numeric(0:783), c(1L,28L,28L,1L))$requires_grad_()
    patches <- nn$MaePatches(x)
    testthat::expect_equal(nn$MaeImage(patches)$values(), x$values())
    testthat::expect_equal(nn$MaePixel(5L,0L),203)
    testthat::expect_equal(nn$grad(nn$sum(nn$MaeImage(patches)),list(x))[[1L]]$values(),rep(1,784))
    ids <- nn$cast(nn$from_vector_double(c(0,4294967295),2L),nn$DType$Int64)
    for (seed in c(0,4294967295)) {
        s <- nn$MaeSelection(ids,0L,seed)
        testthat::expect_equal(s$shape(),c(2L,4L,16L))
        testthat::expect_false(s$requires_grad())
        testthat::expect_equal(s$values(),nn$MaeSelection(ids,0L,seed)$values())
        testthat::expect_equal(sum(nn$sum(s,1L)$values()==1),8)
    }
    testthat::expect_error(nn$MaeSelection(nn$from_vector(1,1L)),"integral")
    testthat::expect_error(nn$MaePixel(16L,0L),"range")
})

testthat::test_that("native MAE outputs retain ownership and full parameter gradients", {
    nn <- datamungerNN::nn
    p <- nn$ParameterStore(1877L)
    x <- nn$from_vector((((0:1567)*17) %% 97)/96,c(2L,28L,28L,1L))
    testthat::expect_true(all(x$values() >= 0 & x$values() <= 1))
    ids <- nn$cast(nn$from_vector(c(7,11),2L),nn$DType$Int64)
    s <- nn$MaeSelection(ids)
    result <- nn$MaskedAutoencoder(p,x,s)
    testthat::expect_equal(p$size(),35L)
    testthat::expect_equal(p$count(),13649)
    testthat::expect_equal(result$code$shape(),c(2L,4L,32L))
    testthat::expect_equal(result$encoder_attention$shape(),c(2L,2L,4L,4L))
    testthat::expect_equal(result$decoder_attention$shape(),c(2L,2L,16L,16L))
    code <- result$code; prediction <- result$prediction; target <- result$patches; mask <- result$mask
    expected <- prediction$values()
    rm(result); invisible(gc())
    testthat::expect_equal(prediction$values(),expected)
    testthat::expect_equal(nn$MaeDecode(p,code,s)$prediction$values(),expected)
    derivatives <- nn$grad(nn$MaeLoss(prediction,target,mask),p$parameters())
    testthat::expect_length(derivatives,35L)
    testthat::expect_true(all(vapply(derivatives,function(g) all(is.finite(g$values())) && any(g$values()!=0),logical(1))))
    testthat::expect_false(nn$MaeEncode(p,x,s)$prediction$defined())
    testthat::expect_false(nn$MaeDecode(p,code,s)$patches$defined())
    empty <- nn$ParameterStore(1L)
    testthat::expect_error(nn$MaskedAutoencoder(empty,x,nn$zeros(c(2L,4L,16L))),"distinct|one-hot")
    testthat::expect_equal(empty$size(),0L)
    y <- nn$full(c(1L,2L,2L),.3)$requires_grad_()
    loss <- nn$MaeLoss(y,nn$full(c(1L,2L,2L),.7),nn$from_vector(c(0,1),c(1L,2L)))
    testthat::expect_lt(abs(loss$item()-.16),1e-7)
    testthat::expect_equal(nn$grad(loss,list(y))[[1L]]$values(),c(0,0,-.4,-.4),tolerance=1e-7)
})
