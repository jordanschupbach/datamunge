#!/usr/bin/env python3
"""Regenerate the Vulkan AXPY fixture from its checked-in GLSL source.

Uses glslc or glslangValidator on PATH, or --shaderc-library for a shaderc shared
library. No compiler/SDK is needed to consume the generated test fixture.
"""
import argparse
import ctypes as C
import hashlib
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def shaderc_compile(library, source, filename='axpy.comp'):
    """Compile compute GLSL through the official shaderc C API and release all handles."""
    lib = C.CDLL(str(library))
    signatures = {
        'shaderc_compiler_initialize': ([], C.c_void_p),
        'shaderc_compile_into_spv': ([C.c_void_p, C.c_char_p, C.c_size_t, C.c_int, C.c_char_p, C.c_char_p, C.c_void_p], C.c_void_p),
        'shaderc_result_get_compilation_status': ([C.c_void_p], C.c_int),
        'shaderc_result_get_error_message': ([C.c_void_p], C.c_char_p),
        'shaderc_result_get_length': ([C.c_void_p], C.c_size_t),
        'shaderc_result_get_bytes': ([C.c_void_p], C.c_void_p),
        'shaderc_result_release': ([C.c_void_p], None),
        'shaderc_compiler_release': ([C.c_void_p], None),
    }
    for name, (arguments, result) in signatures.items():
        function = getattr(lib, name)
        function.argtypes = arguments
        function.restype = result
    compiler = lib.shaderc_compiler_initialize()
    if not compiler:
        raise RuntimeError('shaderc compiler initialization failed')
    result = None
    try:
        result = lib.shaderc_compile_into_spv(compiler, source, len(source), 2, filename.encode(), b'main', None)
        if not result:
            raise RuntimeError('shaderc returned no compilation result')
        if lib.shaderc_result_get_compilation_status(result):
            raise RuntimeError(lib.shaderc_result_get_error_message(result).decode())
        return C.string_at(lib.shaderc_result_get_bytes(result), lib.shaderc_result_get_length(result))
    finally:
        if result:
            lib.shaderc_result_release(result)
        lib.shaderc_compiler_release(compiler)


def main():
    """Compile and deterministically embed little-endian SPIR-V words."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--shaderc-library', type=Path)
    args = parser.parse_args()
    fixture = ROOT / 'tests/fixtures/compute'
    source = (fixture / 'axpy.comp').read_bytes()
    if args.shaderc_library:
        code = shaderc_compile(args.shaderc_library, source)
    else:
        compiler = shutil.which('glslc') or shutil.which('glslangValidator')
        if not compiler:
            parser.error('install glslc/glslangValidator, or supply --shaderc-library')
        with tempfile.TemporaryDirectory(prefix='compute-shader-') as directory:
            path = Path(directory) / 'axpy.spv'
            command = [compiler, '-V'] if Path(compiler).name == 'glslangValidator' else [compiler]
            subprocess.run(command + ['-o', str(path), 'axpy.comp'], cwd=fixture, check=True)
            code = path.read_bytes()
    if len(code) % 4 or code[:4] != b'\x03\x02\x23\x07':
        raise RuntimeError('compiler did not produce little-endian SPIR-V')
    words = struct.unpack('<' + 'I' * (len(code) // 4), code)
    lines = [f'// Generated by scripts/compile_compute_fixture.py; source SHA-256 {hashlib.sha256(source).hexdigest()}.',
             '#pragma once', '#include <cstdint>', 'namespace compute_fixture {',
             'inline constexpr std::uint32_t axpy_spirv[]={']
    lines += [' ' + ','.join(hex(word) + 'u' for word in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
    lines += ['};', '} // namespace compute_fixture', '']
    (fixture / 'axpy_spirv.hpp').write_text('\n'.join(lines))
    print(f'Embedded {len(words)} SPIR-V words')


if __name__ == '__main__':
    main()
