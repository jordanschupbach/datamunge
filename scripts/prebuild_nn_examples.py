def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-swig", action="store_true")
    args = parser.parse_args()
    print(f"Generated {len(generate(not args.no_swig))} NN example bindings")


if __name__ == "__main__":
    main()
