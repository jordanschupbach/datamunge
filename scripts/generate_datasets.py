#!/usr/bin/env python3
"""Embed data-raw/datasets/*.csv into the library as C++ sources.

Each dataset becomes src/datamunge/datasets/embedded/<name>.cpp holding the CSV
text as raw string literals, plus a shared declarations header. The library
parses the text with datasets::parse_csv() at call time, so the CSV files stay
the single source of truth. Output is deterministic; run `just generate-datasets`.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data-raw" / "datasets"
OUT = ROOT / "src" / "datamunge" / "datasets" / "embedded"

# Name of each built-in CSV (without extension), in declaration order.
DATASETS = [
    "air_passengers",
    "airquality",
    "breast_cancer",
    "diabetes",
    "digits",
    "eight_schools",
    "faithful",
    "misra1a",
    "mtcars",
    "orthodont",
    "titanic",
    "volcano",
    "wine",
]

# MSVC rejects single string literals over ~16 KB, so split at line ends.
CHUNK_BYTES = 12000
DELIMITER = "dmcsv"
HEADER = "// Generated by scripts/generate_datasets.py from data-raw/datasets. Do not edit.\n"


def chunks(text):
    """Splits text into pieces of at most CHUNK_BYTES that end on a newline."""
    piece = []
    size = 0
    for line in text.splitlines(keepends=True):
        if piece and size + len(line) > CHUNK_BYTES:
            yield "".join(piece)
            piece, size = [], 0
        piece.append(line)
        size += len(line)
    if piece:
        yield "".join(piece)


def source(name, text):
    """Returns the C++ translation unit embedding one dataset's CSV text."""
    if f"){DELIMITER}\"" in text:
        raise ValueError(f"{name}.csv contains the raw-string delimiter")
    literals = ",\n".join(f'    R"{DELIMITER}({c}){DELIMITER}"' for c in chunks(text))
    return (
        HEADER
        + f"/// @file {name}.cpp\n"
        + f"/// @brief The built-in {name} dataset: data-raw/datasets/{name}.csv as C++ literals.\n\n"
        + '#include "../embedded_csv.hpp"\n\n'
        + "/// @brief Internal accessors for the CSV text compiled into the library.\n"
        + "namespace datamunge::datasets::detail {\n\n"
        + f"/// @brief Storage for the {name} CSV chunks.\n"
        + "namespace {\n"
        + f"/// @brief The CSV text of data-raw/datasets/{name}.csv, split into short literals.\n"
        + "constexpr const char* kChunks[] = {\n"
        + literals
        + ",\n};\n"
        + "} // namespace\n\n"
        + f"std::string {name}_csv() {{ return join_chunks(kChunks, std::size(kChunks)); }}\n\n"
        + "} // namespace datamunge::datasets::detail\n"
    )


def header():
    """Returns the header declaring every embedded dataset's CSV accessor."""
    lines = [
        HEADER,
        "#pragma once\n\n",
        "/// @file embedded_csv.hpp\n",
        "/// @brief Accessors for the CSV text compiled into the library (see data-raw/datasets).\n\n",
        "#include <cstddef>\n#include <iterator>\n#include <string>\n\n",
        "/// @brief Internal accessors for the CSV text compiled into the library.\n",
        "namespace datamunge::datasets::detail {\n\n",
        "/// @brief Concatenates @p count literal pieces into one string.\n",
        "inline std::string join_chunks(const char* const* chunks, std::size_t count) {\n",
        "  std::string text;\n",
        "  for (std::size_t i = 0; i < count; ++i) text += chunks[i];\n",
        "  return text;\n",
        "}\n\n",
    ]
    for name in DATASETS:
        lines.append(f"/// @brief The CSV text of data-raw/datasets/{name}.csv.\n")
        lines.append(f"std::string {name}_csv();\n")
    lines.append("\n} // namespace datamunge::datasets::detail\n")
    return "".join(lines)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT.parent / "embedded_csv.hpp").write_text(header())
    for name in DATASETS:
        text = (RAW / f"{name}.csv").read_text().replace("\r\n", "\n")
        (OUT / f"{name}.cpp").write_text(source(name, text))
    print(f"Embedded {len(DATASETS)} datasets into {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
