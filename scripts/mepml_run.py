#!/usr/bin/env python3
"""Run the code blocks of .mepml documents and write their results, as mep does.

mep runs a block when you press C-c C-c (or its play button) in the editor, and
`mep-mepml build` only exports the results already in the file. This script is
the headless version of "run every block", so a report can be regenerated by a
`just` recipe or in CI:

  - Each fenced block ```{lang, ...}``` in a supported language is run in the
    document's directory, unless it has eval="no"/"false" (or echo-only
    options such as include=). C and C++ blocks are compiled with `c++`/`cc`
    and the block's flags="..." (shell-expanded, so $(pkg-config ...) works).
  - Its stdout replaces the block's `// result_begin:` ... `// result_end`
    results, which are created under the block if missing.
    results="markdown" (or md/asis/raw) writes the output as-is, unprefixed,
    under `// result_begin: markdown`, so tables become document tables.
  - A block with file="path" draws a figure: as in mep, the newest file with
    that extension the program wrote under the document's directory is copied
    to `path` (MEP_FILE also holds that path for a program that writes it
    itself) and an `\\image(path)` line ends the results.

A block that fails to compile or run leaves the document unchanged and makes
the script exit non-zero, with the error printed.

usage: scripts/mepml_run.py [-j N] FILE.mepml...
"""
import argparse
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys
import tempfile
import threading
import time

FENCE = re.compile(r"^```\{(?P<lang>[\w+#-]+)\s*(?:,(?P<opts>.*))?\}\s*$")
OPTION = re.compile(r'\s*([\w-]+)\s*(?:=\s*("(?:[^"\\]|\\.)*"|[^,]*))?\s*(?:,|$)')
MARKDOWN_RESULTS = {"markdown", "md", "asis", "raw"}
NO = {"no", "false", "nil", "0"}

# How each language runs: (source suffix, compile command or None, run command).
# {src}/{bin} are paths, {flags} the block's flags option. Compiles run in
# parallel; the programs themselves run one at a time, so the picture a
# file= block finds is the one its own program wrote.
RUNNERS = {
    "cpp": (".cpp", "c++ {src} -o {bin} {flags}", "{bin}"),
    "c++": (".cpp", "c++ {src} -o {bin} {flags}", "{bin}"),
    "c": (".c", "cc {src} -o {bin} {flags}", "{bin}"),
    "bash": (".sh", None, "bash {src}"),
    "sh": (".sh", None, "sh {src}"),
    "python": (".py", None, "python3 {src}"),
}
RUN_LOCK = threading.Lock()


def parse_options(text):
    opts = {}
    for m in OPTION.finditer(text or ""):
        key, value = m.group(1), m.group(2)
        if not key:
            continue
        if value is None:
            value = "yes"
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = value[1:-1].replace('\\"', '"')
        opts[key] = value
    return opts


def find_blocks(lines):
    """Each runnable block as (fence index, closing index, lang, options, code)."""
    blocks, i = [], 0
    while i < len(lines):
        m = FENCE.match(lines[i])
        if not m:
            i += 1
            continue
        end = i + 1
        while end < len(lines) and lines[end].rstrip() != "```":
            end += 1
        lang, opts = m.group("lang").lower(), parse_options(m.group("opts"))
        runnable = (
            lang in RUNNERS
            and opts.get("eval", "yes").lower() not in NO
            and "include" not in opts
        )
        if runnable:
            blocks.append((i, end, lang, opts, lines[i + 1:end]))
        i = end + 1
    return blocks


def results_span(lines, close):
    """(start, stop) of the results under the block closing at `close`, or None."""
    start = close + 1
    if start < len(lines) and lines[start].startswith("// result_begin"):
        stop = start
        while stop < len(lines) and lines[stop].rstrip() != "// result_end":
            stop += 1
        return start, stop + 1
    return None


def format_results(output, markdown, image=None):
    """mep's own layout of a block's results (mepml_doc.cpp, FormatResults)."""
    body = [ln.rstrip("\r") for ln in output.rstrip("\r\n").split("\n")] if output.strip() else []
    if markdown:
        # The blank lines a printer puts around a table are dropped.
        while body and not body[0].strip():
            body.pop(0)
        while body and not body[-1].strip():
            body.pop()
        lines = ["// result_begin: markdown"] + body
        if image:
            lines.append("\\image(%s)" % image)
    else:
        lines = ["// result_begin:"] + ["//" if not ln else "// " + ln for ln in body]
        if image:
            lines.append("// \\image(%s)" % image)
    lines.append("// result_end")
    return lines


def pictures(root, ext):
    """{path: mtime} of every file with extension `ext` under `root`."""
    found = {}
    for dirpath, _, files in os.walk(root):
        for f in files:
            if f.endswith(ext):
                p = os.path.join(dirpath, f)
                found[p] = os.path.getmtime(p)
    return found


def prepare_block(doc_dir, lang, opts, code):
    """Compile a block in parallel; retain its temporary files until execution."""
    suffix, compile_cmd, run_cmd = RUNNERS[lang]
    tmp = tempfile.TemporaryDirectory()
    try:
        src = os.path.join(tmp.name, "block" + suffix)
        exe = os.path.join(tmp.name, "block")
        with open(src, "w") as f:
            f.write("\n".join(code) + "\n")
        fmt = dict(src=src, bin=exe, flags=opts.get("flags", ""))
        if compile_cmd:
            c = subprocess.run(compile_cmd.format(**fmt), shell=True, cwd=doc_dir,
                               capture_output=True, text=True, timeout=900)
            if c.returncode != 0:
                raise RuntimeError(f"compile failed\n{c.stdout}{c.stderr}")
        return tmp, run_cmd.format(**fmt)
    except BaseException:
        tmp.cleanup()
        raise


def execute_block(doc_dir, opts, prepared):
    """Execute in document order, so later blocks can consume earlier artifacts."""
    tmp, command = prepared
    figure = opts.get("file")
    try:
        env = dict(os.environ)
        if figure:
            env["MEP_FILE"] = os.path.join(doc_dir, figure)
        with RUN_LOCK:
            before = pictures(doc_dir, os.path.splitext(figure)[1]) if figure else {}
            started = time.time()
            r = subprocess.run(command, shell=True, cwd=doc_dir, env=env,
                               capture_output=True, text=True, timeout=900)
            if r.returncode != 0:
                raise RuntimeError(f"exit {r.returncode}\n{r.stdout}{r.stderr}")
            if figure:
                claim_picture(doc_dir, figure, before, started)
        return r.stdout, figure
    finally:
        tmp.cleanup()


def claim_picture(doc_dir, figure, before, started):
    """Copy the newest picture the program wrote to file= (what mep does)."""
    target = os.path.join(doc_dir, figure)
    after = pictures(doc_dir, os.path.splitext(figure)[1])
    new = [p for p, t in after.items()
           if os.path.abspath(p) != os.path.abspath(target)
           and (p not in before or t > before[p]) and t >= started - 1]
    if new:
        newest = max(new, key=after.get)
        os.makedirs(os.path.dirname(target) or ".", exist_ok=True)
        shutil.copyfile(newest, target)
    elif not (os.path.exists(target) and os.path.getmtime(target) >= started - 1):
        raise RuntimeError(f"the block did not write a {os.path.splitext(figure)[1]} picture for file={figure}")


def run_document(path, jobs):
    with open(path) as f:
        lines = f.read().split("\n")
    doc_dir = os.path.dirname(os.path.abspath(path))
    blocks = find_blocks(lines)
    with concurrent.futures.ThreadPoolExecutor(jobs) as pool:
        futures = [pool.submit(prepare_block, doc_dir, lang, opts, code)
                   for (_, _, lang, opts, code) in blocks]
        outcomes = []
        for block, fut in zip(blocks, futures):
            try:
                outcomes.append(execute_block(doc_dir, block[3], fut.result()))
            except Exception as e:  # noqa: BLE001 - report every failing block
                outcomes.append(e)
    failures = [(b, o) for b, o in zip(blocks, outcomes) if isinstance(o, Exception)]
    if failures:
        for (start, _, lang, _, _), err in failures:
            print(f"--- {path}:{start + 1}: {lang} block failed\n{str(err)[-3000:]}", file=sys.stderr)
        return False
    # Replace from the bottom so earlier line numbers stay valid.
    for (start, close, lang, opts, _), (output, figure) in reversed(list(zip(blocks, outcomes))):
        markdown = opts.get("results", "output").lower() in MARKDOWN_RESULTS
        new = format_results(output, markdown, figure)
        span = results_span(lines, close)
        if span:
            lines[span[0]:span[1]] = new
        else:
            lines[close + 1:close + 1] = new
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"ran {len(blocks)} block(s) in {path}")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-j", type=int, default=os.cpu_count() or 4, help="blocks run in parallel per document")
    ap.add_argument("files", nargs="+")
    a = ap.parse_args()
    ok = all([run_document(p, a.j) for p in a.files])
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
