#!/usr/bin/env python3
"""Audit genuine language ports against every canonical C++ NN example."""
import argparse
import collections
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUS = ROOT / "examples/nn/language_status.json"


def sources():
    migrated = ROOT / "examples/cpp/nn"
    original = ROOT / "examples/nn"
    found = [(p, p.relative_to(migrated)) for p in migrated.glob("[12]_*/**/*.cpp")]
    found += [(p, p.relative_to(original)) for p in original.glob("[0-9]*/**/*.cpp")]
    names = [p.stem for p, _ in found]
    if len(names) != len(set(names)):
        raise ValueError("duplicate canonical example names")
    return sorted(found, key=lambda item: item[1].as_posix())


def refresh(write_catalog=True):
    prior_report = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    previous = prior_report.get("examples", {})
    api_digest = hashlib.sha256()
    dependencies = sorted((ROOT / "include/datamunge/nn").glob("*.hpp")) + sorted(
        (ROOT / "src/datamunge/nn").glob("*.cpp")
    )
    dependencies += [
        ROOT / "prebindings/nn/src/nn.i",
        ROOT / "src/pydatamunge/nn.py",
        ROOT / "src/pydatamunge/nn_workflows.py",
        ROOT / "prebindings/nn/r/R/nn.R",
        ROOT / "examples/r/nn/common.R",
    ]
    for dependency in dependencies:
        api_digest.update(dependency.relative_to(ROOT).as_posix().encode())
        api_digest.update(dependency.read_bytes())
    api_sha256 = api_digest.hexdigest()
    entries = {}
    for source, relative in sources():
        old = previous.get(source.stem, {})
        record = dict(
            cpp=source.relative_to(ROOT).as_posix(),
            cpp_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            classification=old.get("classification"),
        )
        if (
            old.get("cpp_sha256") == record["cpp_sha256"]
            and prior_report.get("api_sha256") == api_sha256
            and old.get("cpp_reference_validation")
        ):
            record["cpp_reference_validation"] = old["cpp_reference_validation"]
        for language, suffix, marker in [
            ("python", ".py", "# Native Python NN example"),
            ("r", ".R", "# Native R NN example"),
        ]:
            path = ROOT / "examples" / language / "nn" / relative.with_suffix(suffix)
            text = path.read_text() if path.exists() else ""
            state = (
                "native"
                if text.startswith(marker)
                else ("reference_wrapper" if text else "missing")
            )
            digest = hashlib.sha256(text.encode()).hexdigest() if text else None
            saved = old.get(language, {})
            evidence = (
                saved.get("validation")
                if saved.get("sha256") == digest
                and old.get("cpp_sha256") == record["cpp_sha256"]
                and prior_report.get("api_sha256") == api_sha256
                else None
            )
            record[language] = dict(
                path=path.relative_to(ROOT).as_posix(),
                implementation=state,
                sha256=digest,
                validation=evidence,
            )
        entries[source.stem] = record
    result = dict(
        schema=1,
        total=len(entries),
        test_epoch_limit=5,
        api_sha256=api_sha256,
        examples=entries,
    )
    text = json.dumps(result, indent=2) + "\n"
    if not STATUS.exists() or STATUS.read_text() != text:
        STATUS.write_text(text)
    if not write_catalog:
        # The catalogue lives in the nix build source; concurrent port validation leaves it alone.
        return result
    catalogue = "# Generated by scripts/nn_migration_status.py.\nEXAMPLES = {\n"
    for source, relative in sources():
        catalogue += f"    {source.stem!r}: {relative.as_posix()!r},\n"
    catalogue += (
        "}\n\nNATIVE_EXAMPLES = "
        + repr(
            tuple(
                name
                for name, value in entries.items()
                if value["python"]["implementation"] == "native"
            )
        )
        + "\n"
    )
    path = ROOT / "src/pydatamunge/_nn_catalog.py"
    if not path.exists() or path.read_text() != catalogue:
        path.write_text(catalogue)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--classification", nargs=2, metavar=("NAME", "yes|no"))
    args = parser.parse_args()
    report = (
        refresh()
        if args.refresh or not STATUS.exists()
        else json.loads(STATUS.read_text())
    )
    if args.classification:
        name, value = args.classification
        if value not in ("yes", "no"):
            parser.error("classification must be yes or no")
        report["examples"][name]["classification"] = value == "yes"
        STATUS.write_text(json.dumps(report, indent=2) + "\n")
    print(f"Canonical NN examples: {report['total']}")
    for language in ("python", "r"):
        counts = collections.Counter(
            v[language]["implementation"] for v in report["examples"].values()
        )
        validated = sum(
            v[language]["validation"] is not None for v in report["examples"].values()
        )
        print(f"{language}: {dict(counts)}; validated={validated}")


if __name__ == "__main__":
    main()
