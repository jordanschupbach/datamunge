#!/usr/bin/env python3
"""Exact integer/Fraction frame and floor-bin fixtures; no double recurrence replay."""
from pathlib import Path
from fractions import Fraction
import argparse,random,math

def render():
 rng=random.Random(133082);rows=[]
 for _ in range(1024):
  a,b,p=[tuple(Fraction(rng.randrange(-16,17),4) for _ in range(2)) for _ in range(3)]
  dx,dy=b[0]-a[0],b[1]-a[1];den=dx*dx+dy*dy
  if not den:continue
  ax,ay=p[0]-a[0],p[1]-a[1];u=(ax*dx+ay*dy)/den;v=(ay*dx-ax*dy)/den
  q=Fraction(rng.choice([1,2,4,16]),4)
  vals=[*p,*a,*b,q,u,v,den]
  rows.append('    {'+', '.join(float(x).hex() for x in vals)+f', {math.floor(u/q)}, {math.floor(v/q)}'+'},')
 return '\n'.join(['// Generated by tests/oracles/geometric_hash_fraction.py --write; do not edit.','#pragma once','#include <array>','namespace geometric_hash_fraction {','struct Case {double px,py,ax,ay,bx,by,quant,u,v,length_squared; int cell_u,cell_v;};',f'inline constexpr std::array<Case,{len(rows)}> cases{{{{',*rows,'}};','} // namespace geometric_hash_fraction',''])
def main():
 p=argparse.ArgumentParser();g=p.add_mutually_exclusive_group(required=True);g.add_argument('--write',action='store_true');g.add_argument('--check',action='store_true');a=p.parse_args()
 path=Path(__file__).with_suffix('.hpp');s=render()
 if a.write:path.write_text(s)
 else:assert path.read_text()==s,'regenerate fixtures with --write'
 print('Geometric hashing Fraction fixture verified: '+str(s.count('    {'))+' independent queries')
if __name__=='__main__':main()
