#!/usr/bin/env python3
"""Gnome-sort fixtures from direct stable ranks and inversion counts, without a sort loop.

Use --write to regenerate the adjacent C++ fixture, or --check to verify it.
Python standard library only. Expected original indices are placed by independent
pairwise key/index ranks, not by any comparison-exchange sorting recurrence.
"""
import argparse
import itertools
from pathlib import Path
import random


def inputs():
    for n in range(7):
        yield from itertools.product((-1, 0, 1), repeat=n)
    for n in range(7):
        yield from itertools.permutations(range(n))
    yield (5, 3, 8, 1, 9, 2, 7)
    yield (2**31-1, 0, -2**31, 2**31-1, -2**31)
    rng = random.Random(136)
    for _ in range(128):
        yield tuple(rng.randrange(-20, 21) for _ in range(rng.randrange(21)))


def render():
    values, identities, rows = [], [], []
    for a in inputs():
        n = len(a)
        ranks = [sum(y < x or (y == x and j < i) for j, y in enumerate(a)) for i, x in enumerate(a)]
        ids = [None]*n
        for i, rank in enumerate(ranks):
            ids[rank] = i
        inversions = sum(a[i] > a[j] for i in range(n) for j in range(i+1, n))
        boundary = 1+sum(a[i] < min(a[:i]) for i in range(1, n)) if n else 0
        rows.append((len(values), n, inversions, boundary))
        values.extend(a)
        identities.extend(ids)
    lines = ['// Generated by tests/oracles/gnome_sort_exact.py --write; do not edit.',
             '// Direct key/index ranks, pairwise strict inversions and original prefix minima.',
             '#pragma once', '#include <cstddef>', 'namespace gnome_sort_exact_fixture {',
             'struct Case {std::size_t offset, size, inversions, boundary_visits;};',
             'inline constexpr int values[] = {']
    lines += [','.join(map(str, values[i:i+20]))+',' for i in range(0, len(values), 20)]
    lines += ['};', 'inline constexpr std::size_t original_indices[] = {']
    lines += [','.join(map(str, identities[i:i+20]))+',' for i in range(0, len(identities), 20)]
    lines += ['};', 'inline constexpr Case cases[] = {']
    lines += ['{%d,%d,%d,%d},' % row for row in rows]
    lines += ['};', '} // namespace gnome_sort_exact_fixture', '']
    return '\n'.join(lines), len(rows), len(values)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count, values = render()
    path = Path(__file__).with_suffix('.hpp')
    if args.write:
        path.write_text(content)
    else:
        assert args.check, 'choose --write or --check'
        assert path.read_text() == content, 'regenerate with --write'
    print(f'Exact gnome-sort fixtures: {count} stable-rank cases, {values} input entries')


if __name__ == '__main__':
    main()
