#!/usr/bin/env python3
"""Exact direct Fourier fixtures in Q(sqrt(2)); no Goertzel recurrence.

Generate/check with --write or --check. All ternary signals of lengths 1,2,4 and
all binary +/-1 signals of length8 are evaluated at 0..2N-1. Eighth roots of unity
are exact pairs a+b*sqrt(2) of Fractions. Complex sums and squared magnitudes use
that algebraic field, without a resonator, feedback, trig approximation or FFT.
"""
from fractions import Fraction as F
import argparse
import itertools
from pathlib import Path


def add(z, w):
    return z[0]+w[0], z[1]+w[1]


def mul(z, w):
    return z[0]*w[0]+2*z[1]*w[1], z[0]*w[1]+z[1]*w[0]


def render():
    one, zero, root = (F(1), F(0)), (F(0), F(0)), (F(0), F(1, 2))
    neg = lambda z: (-z[0], -z[1])
    cos = [one, root, zero, neg(root), neg(one), neg(root), zero, root]
    sin = [zero, root, one, root, zero, neg(root), neg(one), neg(root)]
    values, rows = [], []
    for n in (1, 2, 4, 8):
        alphabet = (-1, 1) if n == 8 else (-1, 0, 1)
        for x in itertools.product(alphabet, repeat=n):
            for k in range(2*n):
                re, im = zero, zero
                for t, v in enumerate(x):
                    phase = ((k*t) % n)*(8//n)
                    re = add(re, mul((F(v), F(0)), cos[phase]))
                    im = add(im, mul((F(-v), F(0)), sin[phase]))
                a, b = add(mul(re, re), mul(im, im))
                rows.append((len(values), n, k, a.numerator, a.denominator, b.numerator, b.denominator))
                values.extend(x)
    lines = ['// Generated by tests/oracles/goertzel_exact.py --write; do not edit.',
             '// Exact direct Fourier sum in Q(sqrt(2)), not a Goertzel/FFT recurrence.',
             '#pragma once', '#include <cstddef>', '#include <cstdint>',
             'namespace goertzel_exact_fixture {',
             'struct Case {std::size_t offset, size, bin; std::int64_t a_num, a_den, b_num, b_den;};',
             'inline constexpr int values[] = {']
    lines += [','.join(map(str, values[i:i+24]))+',' for i in range(0, len(values), 24)]
    lines += ['};', 'inline constexpr Case cases[] = {']
    lines += ['{%d,%d,%d,%d,%d,%d,%d},' % row for row in rows]
    lines += ['};', '} // namespace goertzel_exact_fixture', '']
    return '\n'.join(lines), len(rows), len(values)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write', action='store_true')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    content, cases, values = render()
    target = Path(__file__).with_suffix('.hpp')
    if args.write:
        target.write_text(content)
    else:
        assert args.check, 'choose --write or --check'
        assert target.read_text() == content, 'regenerate with --write'
    print(f'Exact direct-DFT fixtures: {cases} algebraic cases, {values} input entries')


if __name__ == '__main__':
    main()
