#!/usr/bin/env python3
"""Exact rational maximizers independent of any golden-section iteration."""
from fractions import Fraction as Q
from pathlib import Path
import argparse

def render():
 cases=[]
 for a in map(Q,[-4,-1,0,2]):
  for width in [Q(1,2),Q(1),Q(4)]:
   for relative in [Q(-1,4),Q(0),Q(1,8),Q(1,3),Q(1,2),Q(7,8),Q(1),Q(5,4)]:
    p=a+width*relative;b=a+width;peak=max(a,min(b,p));cases.append((a,b,p,peak))
 def fmt(x):return f'{x.numerator}.0/{x.denominator}.0'
 text='// Generated by tests/oracles/golden_section_exact.py --write.\n// Algebraic clipped maximizers of -(x-p)^2 and -abs(x-p), no search replay.\n#pragma once\n#include <array>\nnamespace golden_fixture {\nstruct Case { double a,b,p,peak; };\n'
 text+=f'inline constexpr std::array<Case,{len(cases)}> cases{{{{\n'
 text+=''.join('    {'+', '.join(map(fmt,row))+'},\n' for row in cases)
 return text+'}};\n} // namespace golden_fixture\n',len(cases)

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true');args=parser.parse_args();text,n=render();path=Path(__file__).with_suffix('.hpp')
 if args.write:path.write_text(text)
 if args.check:assert path.read_text()==text,'Regenerate exact golden-section fixtures with --write'
 print(f'Exact rational clipped-max fixtures: {n} cases, {2*n} quadratic/absolute maxima')
if __name__=='__main__':main()
