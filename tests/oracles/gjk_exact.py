#!/usr/bin/env python3
"""Regenerate planar GJK fixtures using exact hull geometry, without GJK.

Run with --write after intentional fixture changes, or --check in native checks.
Only Python's standard library is required. Every input coordinate is dyadic;
all pairwise differences, hull predicates and clamped boundary projections use
Fraction. The tested GJK kernel neither imports nor calls this implementation.
"""
from fractions import Fraction as F
from itertools import product
from pathlib import Path
import argparse
import random


def cross(o, a, b):
    return (a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0])


def hull(points):
    points = sorted(set(points))
    if len(points) < 2:
        return points
    lower, upper = [], []
    for dest, seq in ((lower, points), (upper, reversed(points))):
        for p in seq:
            while len(dest) > 1 and cross(dest[-2], dest[-1], p) <= 0:
                dest.pop()
            dest.append(p)
    return lower[:-1]+upper[:-1]


def distance_squared(a, b):
    """Enumerate the full Minkowski hull and every boundary projection exactly."""
    p = hull([(x-u, y-v) for x, y in a for u, v in b])
    if len(p) >= 3 and all(cross(x, y, (0, 0)) >= 0 for x, y in zip(p, p[1:]+p[:1])):
        return F(0)
    if len(p) == 1:
        return p[0][0]**2+p[0][1]**2
    squared = []
    for x, y in zip(p, p[1:]+p[:1]):
        vx, vy = y[0]-x[0], y[1]-x[1]
        t = max(F(0), min(F(1), -(x[0]*vx+x[1]*vy)/(vx*vx+vy*vy)))
        squared.append((x[0]+t*vx)**2+(x[1]+t*vy)**2)
    return min(squared)


def cases():
    corners = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    for am, bm in product(range(1, 16), repeat=2):
        a = [tuple(map(F, p)) for i, p in enumerate(corners) if am >> i & 1]
        b = [(F(x)+F(5, 2), F(y)+F(1, 2)) for i, (x, y) in enumerate(corners) if bm >> i & 1]
        yield a, b
    for am, bm in product(range(1, 32), repeat=2):
        a = [(F(i-2), F(0)) for i in range(5) if am >> i & 1]
        b = [(F(i)-F(3, 2), F(0)) for i in range(5) if bm >> i & 1]
        yield a, b
    rng = random.Random(135)
    for _ in range(256):
        a, b = [], []
        for cloud in (a, b):
            for _ in range(rng.randrange(1, 10)):
                cloud.append((F(rng.randrange(-16, 17), 4), F(rng.randrange(-16, 17), 4)))
        yield a, b


def render():
    points, rows = [], []
    for a, b in cases():
        offset = len(points)
        points.extend(a+b)
        sq = distance_squared(a, b)
        assert 0 <= sq.numerator < 2**64 and 0 < sq.denominator < 2**64
        rows.append((offset, len(a), len(b), sq.numerator, sq.denominator))
    lines = ['// Generated by tests/oracles/gjk_exact.py --write; do not edit.',
             '// Exact full Minkowski hull + exhaustive boundary projections; no GJK.',
             '#pragma once', '#include <datamunge/geometry/point2d.hpp>',
             '#include <cstddef>', '#include <cstdint>', 'namespace gjk_exact_fixture {',
             'struct Case {std::size_t offset, a_size, b_size; std::uint64_t numerator, denominator;};',
             'inline constexpr datamunge::geometry::Point2D points[] = {']
    lines += ['{%s,%s},' % (float(x).hex(), float(y).hex()) for x, y in points]
    lines += ['};', 'inline constexpr Case cases[] = {']
    lines += ['{%d,%d,%d,%dULL,%dULL},' % row for row in rows]
    lines += ['};', '} // namespace gjk_exact_fixture', '']
    return '\n'.join(lines), len(rows), len(points)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count, points = render()
    path = Path(__file__).with_suffix('.hpp')
    if args.write:
        path.write_text(content)
    else:
        assert args.check, 'choose --write or --check'
        assert path.read_text() == content, 'regenerate with --write'
    print(f'Exact GJK hull fixtures: {count} cases, {points} stored points')


if __name__ == '__main__':
    main()
