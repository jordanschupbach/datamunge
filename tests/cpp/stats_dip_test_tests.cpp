TEST(DipTest, StatisticAndModalIntervalMatchDiptest) {
    for (std::size_t c = 0; c < cases.size(); ++c) {
        const auto d = dip_statistic(cases[c].x);
        EXPECT_NEAR(d.statistic,cases[c].dip,1e-14) << c;
        EXPECT_DOUBLE_EQ(d.modal_lower,cases[c].lower) << c;
        EXPECT_DOUBLE_EQ(d.modal_upper,cases[c].upper) << c;
    }
    EXPECT_NEAR(dip_statistic({1,2,3,4,10,11,12,13}).statistic,1.0/6,1e-15);
}

TEST(DipTest, BoundsAndDegenerateSamples) {
    EXPECT_DOUBLE_EQ(dip_statistic({3}).statistic,.5);
    EXPECT_DOUBLE_EQ(dip_statistic({2,2,2,2}).statistic,1.0/8);
    std::mt19937_64 random(3);
    std::normal_distribution<double> normal;
    for (std::size_t n : {10U,50U,200U}) {
        std::vector<double> x(n);
        for (auto& v : x)
            v = normal(random);
        const double d = dip_statistic(x).statistic;
        EXPECT_GE(d,1.0/(2*n));
        EXPECT_LE(d,.25);
    }
}

TEST(DipTest, CalibratedPValueSeparatesUnimodalAndBimodal) {
    std::mt19937_64 random(9);
    std::normal_distribution<double> normal;
    std::vector<double> unimodal(150), bimodal(150);
    for (auto& v : unimodal)
        v = normal(random);
    for (std::size_t i = 0; i < bimodal.size(); ++i)
        bimodal[i] = normal(random)+(i%2 ? 4.0 : 0.0);
    const auto a = dip_test(unimodal,{.replicates=1000});
    const auto b = dip_test(bimodal,{.replicates=1000});
    EXPECT_GT(a.p_value,.2);
    EXPECT_LT(b.p_value,.01);
    EXPECT_DOUBLE_EQ(b.p_value,1.0/1001);
    EXPECT_EQ(dip_test(unimodal,{.replicates=200,.seed=5}).p_value,dip_test(unimodal,{.replicates=200,.seed=5}).p_value);
    EXPECT_THROW((void)dip_test({1,2,3}),std::invalid_argument);
    EXPECT_THROW((void)dip_test(unimodal,{.replicates=0}),std::invalid_argument);
    EXPECT_THROW((void)dip_statistic({}),std::invalid_argument);
    EXPECT_THROW((void)dip_statistic({1,std::nan("")}),std::invalid_argument);
}

