  % viridis_colors  `n` colours of the viridis scale, from dark purple through blue and green to yellow, matching R's `viridisLite::viridis(n)` at n = 10.
  %
  %   r = datamunge.viridis_colors (n)
  %
  %   Viridis is perceptually uniform, so equal steps in value look like equal steps in colour,
  %   and it stays readable in greyscale and for the common forms of colour blindness. Colours are
  %   interpolated linearly between viridis(10)'s ten anchors.
  %
  %   Example:
  %     const auto pal = dm::graphics::viridis_colors(10);
  %     std::print("{} {} {}\n", pal[0].r, pal[5].g, pal[9].b);  // 68 158 37
  %
  %   References:
  %   - S. van der Walt and N. Smith (2015). "mpl colourmaps" (viridis): https://bids.github.io/colormap/
  %   - viridisLite: https://sjmgarnier.github.io/viridisLite/
  %
  %   Inputs:
  %     n  integer: Number of colours (at least 1).
  %
  %   Output:
  %     r  cell array of datamunge.RGB: The palette, low (purple) to high (yellow).
  %
  %   Errors:
  %     datamunge:invalid_argument  If `n` is 0. (C++ std::invalid_argument)
  %
  %   C++: std::vector<RGBA> datamunge::graphics::viridis_colors(std::size_t n)
  %
  %   See also: datamunge.value_colors(), datamunge.terrain_colors()
  r = __datamunge__(131, n);
end
