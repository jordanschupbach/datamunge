function r = dyadic_refine (basis)
  % dyadic_refine  Halves every knot span of a clamped basis (inserts each positive span's midpoint).
  %
  %   r = datamunge.dyadic_refine (basis)
  %
  %   This is the nested-space step between consecutive levels of HB/THB splines: the refined
  %   space contains the coarse one, and the operator maps coefficients exactly.
  %
  %   Example:
  %     auto r = dm::fda::dyadic_refine(dm::fda::BSplineBasis::open_uniform(3, 5));
  %     std::print("{} -> {}\n", 5, r.basis.basis_size()); // 5 -> 7
  %
  %   References:
  %   - E. Cohen, T. Lyche and R. Riesenfeld (1980). Discrete B-splines and subdivision
  %     techniques in computer-aided geometric design and computer graphics.
  %     https://doi.org/10.1016/0146-664X(80)90040-4
  %
  %   Inputs:
  %     basis  datamunge.BSplineBasis: Clamped basis to refine.
  %
  %   Output:
  %     r  datamunge.BSplineRefinement: The refined basis and its refinement operator.
  %
  %   Errors:
  %     datamunge:invalid_argument  If the basis is not clamped. (C++ std::invalid_argument)
  %
  %   C++: BSplineRefinement datamunge::fda::dyadic_refine(const BSplineBasis & basis)
  %
  %   See also: datamunge.refine_basis(), datamunge.dyadic_refine()
  r = __datamunge__(235, basis);
end
