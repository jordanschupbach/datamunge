function r = refine_basis (basis, inserted_knots)
  % refine_basis  Inserts knots into a clamped B-spline basis (Oslo algorithm).
  %
  %   r = datamunge.refine_basis (basis, inserted_knots)
  %
  %   Builds the refined knot vector (old knots merged with `inserted_knots`) and the sparse
  %   discrete-B-spline operator that re-expresses every coarse spline on it exactly. Each
  %   row has at most degree + 1 nonzeros and the work is O(m p^2) for m refined functions.
  %
  %   Example:
  %     auto coarse = dm::fda::BSplineBasis::open_uniform(1, 2);   // knots 0 0 1 1
  %     auto r = dm::fda::refine_basis(coarse, {0.25});
  %     std::print("{}\n", r.apply({0.0, 4.0}));                   // [0, 1, 4]
  %
  %   References:
  %   - E. Cohen, T. Lyche and R. Riesenfeld (1980). Discrete B-splines and subdivision
  %     techniques in computer-aided geometric design and computer graphics. Computer Graphics
  %     and Image Processing 14(2), 87-111. https://doi.org/10.1016/0146-664X(80)90040-4
  %   - W. Boehm (1980). Inserting new knots into B-spline curves. Computer-Aided Design
  %     12(4), 199-201. https://doi.org/10.1016/0010-4485(80)90154-2
  %
  %   Inputs:
  %     basis  datamunge.BSplineBasis: Basis to refine; its knot vector must be clamped (first and last knots repeated degree + 1 times, as produced by BSplineBasis::open_uniform()).
  %     inserted_knots  double vector: Knots to add, strictly inside the domain, in any order. Repeats are allowed while every knot multiplicity stays <= degree + 1.
  %
  %   Output:
  %     r  datamunge.BSplineRefinement: The refined basis and its refinement operator.
  %
  %   Errors:
  %     datamunge:invalid_argument  If the basis is not clamped, a knot is outside the open domain or non-finite, or a multiplicity would exceed degree + 1. (C++ std::invalid_argument)
  %
  %   C++: BSplineRefinement datamunge::fda::refine_basis(const BSplineBasis & basis, const std::vector<double> & inserted_knots)
  %
  %   See also: datamunge.dyadic_refine()
  r = __datamunge__(234, basis, inserted_knots);
end
