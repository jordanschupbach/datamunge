function r = diverging_colors (n)
  % diverging_colors  `n` colours from dark blue through white to dark red, a diverging palette for signed values such as correlations (ColorBrewer's RdBu, reversed so that low is blue).
  %
  %   r = datamunge.diverging_colors (n)
  %
  %   Interpolates linearly between the seven RdBu anchor colours; an odd `n` puts pure
  %   near-white (247, 247, 247) in the middle, so with `z_min = -z_max` in RPlot::image() zero
  %   maps to white.
  %
  %   Example:
  %     const auto pal = dm::graphics::diverging_colors(3);
  %     std::print("{} {} {}\n", pal[0].r, pal[1].g, pal[2].r);  // 33 247 178
  %
  %   References:
  %   - C. Brewer, ColorBrewer 2.0 (RdBu scheme): https://colorbrewer2.org
  %
  %   Inputs:
  %     n  integer: Number of colours (at least 1; 1 gives the white midpoint).
  %
  %   Output:
  %     r  cell array of datamunge.RGB: The palette, low (blue) to high (red).
  %
  %   Errors:
  %     datamunge:invalid_argument  If `n` is 0. (C++ std::invalid_argument)
  %
  %   C++: std::vector<RGBA> datamunge::graphics::diverging_colors(std::size_t n)
  %
  %   See also: datamunge.terrain_colors(), datamunge.image()
  r = __datamunge__(130, n);
end
