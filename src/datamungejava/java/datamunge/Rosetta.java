    private static Object reflect(Object self, String name, Object[] a) throws Throwable {
        for (final java.lang.reflect.Method method : self.getClass().getMethods()) {
            if (!method.getName().equals(name) || method.getParameterCount() != a.length - 1) continue;
            try { return method.invoke(self, Arrays.copyOfRange(a, 1, a.length)); }
            catch (java.lang.reflect.InvocationTargetException error) { throw error.getCause(); }
        }
        throw noOverride(self, -1);
    }
