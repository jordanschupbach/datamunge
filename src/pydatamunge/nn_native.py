def _set_doc(obj, text):
    """obj.__doc__ = text, also for native functions and methods (whose __doc__ is read-only).

    A native constructor's text is appended to its class's docstring, which lists the
    constructor signatures."""
    if type(obj).__name__ == "wrapper_descriptor" and obj.__name__ == "__init__":
        owner = obj.__objclass__
        owner.__doc__ = (owner.__doc__ + "\n\n" if owner.__doc__ else "") + text
    else:
        _nn_native._set_doc(obj, text)


