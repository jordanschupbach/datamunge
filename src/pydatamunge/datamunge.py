"""Python interface to the datamunge C++ library.

The classes and functions come from the native ``_datamunge`` extension, generated by
Rosetta from src/pydatamunge/rosetta (bindings.hpp and policy.json). This module adds
the pure-Python conveniences that have no C++ counterpart.
"""

from ._datamunge import *  # noqa: F401,F403
from . import _datamunge
from ._datamunge import _Pair, _Vector

# C++ sequences convert to and from Python lists and tuples. Results come back as
# _Vector (a list with std::vector's size()/push_back()/...) and _Pair (a tuple with
# .first/.second). These names keep the container classes of the former SWIG
# interface: DVector() is an empty _Vector and DPair(1.0, 2.0) a pair.
DVector = IVector = SVector = SizeVector = ByteVector = _Vector
DVectorVector = IVectorVector = StringVectorVector = _Vector
IPairVector = VertexWeightPairVector = _Vector
RGBVector = DataSeriesVector = ABLineVector = LegendEntryVector = _Vector
Point2DVector = Point2DVectorVector = TriangleVector = ImageVector = _Vector
CornerVector = KeyPointVector = HoughLineVector = HoughCircleVector = FlowVectorVector = _Vector
KalmanStateVector = AlphaBetaStateVector = AlphaBetaGammaStateVector = _Vector
PolynomialVector = MultivariatePolynomialVector = SquareFreeFactorVector = _Vector
ComplexVector = BSplineBasisVector = _Vector
IPair = DPair = SPair = DVectorPair = VertexWeightPair = _Pair

BSR = BSplineRegression
PSR = PSplineRegression
RGBA = RGB


def _image_loader_iter(self):
    """Yields the remaining batches of the current epoch; call reset() for the next epoch."""
    while self.has_next():
        yield self.next()


def _csv_reader_iter(self):
    """Yields the remaining chunks as DataFrames."""
    while self.has_next():
        yield self.next()


ImageLoader.__iter__ = _image_loader_iter
ImageLoader.__len__ = lambda self: self.num_batches()
CsvReader.__iter__ = _csv_reader_iter

del _image_loader_iter, _csv_reader_iter
