/// @file datasets.hpp
/// @brief Example datasets as ready-made DataFrames, plus loaders for the large ones.
///
/// Three kinds, by size (catalog() lists them all):
/// - built in: iris(), penguins(), tooth_growth(), wine(), titanic(), ... are compiled into the
///   library, so they need no files or network access;
/// - downloaded: diamonds() and california_housing() fetch a CSV once into the cache (see
///   download.hpp), then read it into memory;
/// - streamed: MNIST, Fashion-MNIST and CIFAR-10/100 are read batch by batch through
///   ImageLoader (image_loader.hpp) and never held in memory whole. CsvReader (csv.hpp) does
///   the same for any CSV file too big to load.
///
/// Every function returns a fresh DataFrame that the caller owns and may freely modify.
///
/// @code
/// const auto iris = dm::datasets::iris();
/// std::print("{}\n", iris.head(10));             // first 10 of 150 rows
/// std::print("{}\n", dm::datasets::catalog());   // every dataset, its size and kind
/// @endcode

#include <datamunge/datasets/csv.hpp>
#include <datamunge/datasets/download.hpp>
#include <datamunge/datasets/generators.hpp>
#include <datamunge/datasets/image_loader.hpp>
#include <datamunge/dstruct/dataframe.hpp>

#include <string>

/// @brief Example datasets: R's `datasets`/`palmerpenguins` classics, scikit-learn's toy sets,
///        and loaders for larger downloaded data.
namespace datamunge::datasets {

/// @brief NIST StRD Misra1a monomolecular-adsorption measurements (Misra, 1978).
/// Fourteen rows in original order, two numeric columns: pressure (x) and volume (y).
/// No missing values. Units are not specified by the source and are left unspecified.
/// Model: volume=A*(1-exp(-b*pressure)); NIST certifies A=238.94212918,
/// b=.00055015643181 and residual SSE=.12455138894. This is observed data, not
/// generated from those certified parameters. The embedded CSV is regenerated by
/// just generate-datasets; no network or external file is needed at runtime.
/// @return New 14-by-2 frame owned by the caller, independent of previous calls.
/// @par Example
/// @code
/// const auto d=dm::datasets::misra1a();
/// std::print("{} {:.2f}\n",d.nrows(),d.double_at("volume",0)); // 14 10.07
/// @endcode
/// @par References
/// - NIST/ITL Statistical Reference Datasets, Misra1a (Misra, 1978).
///   https://www.itl.nist.gov/div898/strd/nls/data/LINKS/DATA/Misra1a.dat
/// @see load(), catalog()
dstruct::DataFrame misra1a();

/// @brief Fisher/Anderson's iris dataset, identical to R's built-in `datasets::iris`.
///
/// 150 rows (50 per species, grouped by species in R's order) and 5 columns:
/// - `Sepal.Length`, `Sepal.Width`, `Petal.Length`, `Petal.Width` -- numeric, in cm;
/// - `Species` -- string: "setosa", "versicolor" or "virginica".
///
/// There are no missing values. Read the numeric columns with `get_column("Sepal.Length")`
/// and the species with `get_column<std::string>("Species")`.
///
/// @return A new 150 x 5 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto iris = dm::datasets::iris();
/// std::print("{}\n", iris.head(3));   // 3 x 5: 5.1, 3.5, 1.4, 0.2, setosa ...
/// const auto& width = iris.get_column("Sepal.Width").values();   // 150 doubles
/// const auto means = iris | dm::group_by("Species") | dm::summarise_each(dm::mean);
/// @endcode
/// @see penguins(), tooth_growth()
dstruct::DataFrame iris();

/// @brief The Palmer Archipelago penguins dataset, matching `palmerpenguins::penguins`.
///
/// 344 rows and 8 columns, in this order:
/// - `species` -- string: "Adelie", "Chinstrap" or "Gentoo";
/// - `island` -- string: "Biscoe", "Dream" or "Torgersen";
/// - `bill_length_mm`, `bill_depth_mm`, `flipper_length_mm`, `body_mass_g` -- numeric;
/// - `sex` -- string: "male" or "female";
/// - `year` -- numeric: 2007, 2008 or 2009.
///
/// Unlike iris, this dataset has missing values (stored as nulls, printed as `NA`): each of
/// the four measurement columns has 2 nulls and `sex` has 11. Use
/// `Row::get_optional_double()` or `DataFrame::drop_nulls()` when working with them --
/// `Row::get_double()` throws on a null cell, and summarise_each() gives a null result for any
/// group containing one.
///
/// @return A new 344 x 8 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto penguins = dm::datasets::penguins();
/// std::print("{}\n", dm::info(penguins));   // 344 rows x 8 columns, null counts per column
/// const auto complete = penguins.drop_nulls();   // 333 rows
/// @endcode
/// @see iris(), tooth_growth()
dstruct::DataFrame penguins();

/// @brief Crampton's guinea pig tooth growth dataset, identical to R's `datasets::ToothGrowth`.
///
/// 60 rows and 3 columns, in this order:
/// - `len` -- numeric: odontoblast length;
/// - `supp` -- string: supplement type, "VC" (ascorbic acid) or "OJ" (orange juice);
/// - `dose` -- numeric: vitamin C dose in mg/day, 0.5, 1 or 2.
///
/// Rows follow R's order: the 30 "VC" rows first, then the 30 "OJ" rows, each block sorted by
/// dose with 10 animals per (supp, dose) cell. There are no missing values.
///
/// @return A new 60 x 3 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto tooth = dm::datasets::tooth_growth();
/// const auto means = tooth | dm::group_by("supp") | dm::summarise_each(dm::mean);
/// std::print("{}\n", means);   // 2 x 3: VC len 16.9633, OJ len 20.6633
/// @endcode
/// @see iris(), penguins()
dstruct::DataFrame tooth_growth();

/// @brief The UCI wine recognition data: chemical analyses of 178 Italian wines from three
///        cultivars, as in scikit-learn's `load_wine()`.
///
/// 178 rows and 14 columns: 13 numeric measurements -- `alcohol`, `malic_acid`, `ash`,
/// `alcalinity_of_ash`, `magnesium`, `total_phenols`, `flavanoids`, `nonflavanoid_phenols`,
/// `proanthocyanins`, `color_intensity`, `hue`, `od280_od315` (OD280/OD315 of diluted wines)
/// and `proline` -- then `cultivar`, a string "class_0" (59 rows), "class_1" (71) or
/// "class_2" (48). No missing values. A classic for LDA, PCA and multiclass classification.
///
/// @return A new 178 x 14 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto wine = dm::datasets::wine();
/// const auto means = wine | dm::group_by("cultivar") | dm::summarise_each(dm::mean);
/// @endcode
/// @see breast_cancer(), iris()
dstruct::DataFrame wine();

/// @brief The Kaggle "Titanic" training set: 891 passengers and whether they survived.
///
/// 891 rows and 12 columns: `PassengerId`, `Survived` (0/1), `Pclass` (1-3), `Name`, `Sex`,
/// `Age`, `SibSp` (siblings/spouses aboard), `Parch` (parents/children aboard), `Ticket`,
/// `Fare`, `Cabin` and `Embarked` ("C", "Q" or "S"). `Name`, `Sex`, `Ticket`, `Cabin` and
/// `Embarked` are strings, the rest numeric. Missing values: `Age` 177, `Cabin` 687,
/// `Embarked` 2 -- a good dataset for showing imputation and logistic regression.
///
/// @return A new 891 x 12 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto titanic = dm::datasets::titanic();
/// const auto rates = titanic | dm::group_by("Sex") | dm::summarise(dm::agg::mean("Survived", "rate"));
/// @endcode
/// @see penguins()
dstruct::DataFrame titanic();

/// @brief The "eight schools" SAT coaching experiment (Rubin 1981), the standard example of
///        a Bayesian hierarchical model.
///
/// 8 rows and 3 columns: `school` (string "A".."H"), `effect` (estimated coaching effect on
/// SAT-V scores) and `std_error` (its standard error). No missing values.
///
/// @return A new 8 x 3 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto schools = dm::datasets::eight_schools();
/// const auto& y = schools.get_column("effect").values();       // 28, 8, -3, 7, -1, 1, 18, 12
/// const auto& sigma = schools.get_column("std_error").values();
/// @endcode
dstruct::DataFrame eight_schools();

/// @brief Orthodontic growth curves (Potthoff and Roy 1964): the distance from the pituitary
///        to the pterygomaxillary fissure of 27 children, measured every two years from age 8
///        to 14. The standard example of a linear mixed model with a random intercept and
///        slope per child.
///
/// 108 rows and 4 columns: `distance` (mm), `age` (years: 8, 10, 12 or 14), `subject`
/// (string "F01".."F11" for the 11 girls, "M01".."M16" for the 16 boys) and `sex`
/// ("Female" or "Male"). Rows are sorted by subject, then age. No missing values.
///
/// @return A new 108 x 4 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto growth = dm::datasets::orthodont();
/// const dm::stats::LMM fit(growth, "distance ~ age + (1 + age | subject)");
/// std::print("{:.4f}\n", fit.coefficients()[1]);  // 0.6602
/// @endcode
///
/// @par References
/// - R. F. Potthoff and S. N. Roy (1964). "A generalized multivariate analysis of variance model
///   useful especially for growth curve problems". Biometrika 51(3/4), 313-326.
///   doi:10.1093/biomet/51.3-4.313
/// - J. C. Pinheiro and D. M. Bates (2000). *Mixed-Effects Models in S and S-PLUS*. Springer.
dstruct::DataFrame orthodont();

/// @brief Monthly international airline passengers, 1949-1960, identical to R's
///        `datasets::AirPassengers` (Box & Jenkins series G).
///
/// 144 rows and 3 numeric columns: `year`, `month` (1-12) and `passengers` (thousands). No
/// missing values. The classic seasonal series: trend, a 12-month cycle, and seasonal swings
/// that grow with the level, so it is usually modelled on the log scale (the "airline model"
/// SARIMA(0,1,1)(0,1,1)_12).
///
/// @return A new 144 x 3 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto air = dm::datasets::air_passengers();
/// const auto& y = air.get_column("passengers").values();   // 112, 118, 132, ...
/// @endcode
dstruct::DataFrame air_passengers();

/// @brief Topographic heights of Maunga Whau (Mt Eden), Auckland, on a 10 m grid, identical to
///        R's `datasets::volcano` in long format.
///
/// 5307 rows (the 87 x 61 grid) and 3 numeric columns: `x` and `y` (metres, 0 to 860 and 0 to
/// 600 in steps of 10) and `elevation` (metres, 94 to 195). `x` follows the rows of R's
/// matrix and `y` its columns (R: "rows correspond to grid lines running east to west and
/// columns to grid lines running south to north"). Rows are ordered by `y`, then `x`. No
/// missing values. The summit (195 m) is at x = 190, y = 300.
///
/// @return A new 5307 x 3 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto v = dm::datasets::volcano();
/// std::print("{}\n", v.double_at("elevation", 0));   // 100
/// @endcode
dstruct::DataFrame volcano();

/// @brief Old Faithful geyser eruptions, identical to R's `datasets::faithful`.
///
/// 272 rows and 2 numeric columns: `eruptions` (eruption time, minutes) and `waiting` (time to
/// the next eruption, minutes). No missing values. Its bimodal shape makes it the classic
/// demonstration for density estimation and two-component mixtures.
///
/// @return A new 272 x 2 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto faithful = dm::datasets::faithful();
/// const auto& waiting = faithful.get_column("waiting").values();
/// @endcode
dstruct::DataFrame faithful();

/// @brief Motor Trend 1974 road tests of 32 cars, identical to R's `datasets::mtcars`.
///
/// 32 rows and 12 columns: `model` (string; R's row names) then the numeric `mpg`, `cyl`,
/// `disp`, `hp`, `drat`, `wt` (1000 lbs), `qsec`, `vs` (0 V-shaped, 1 straight), `am`
/// (0 automatic, 1 manual), `gear` and `carb`. No missing values.
///
/// @return A new 32 x 12 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto cars = dm::datasets::mtcars();
/// const auto by_cyl = cars | dm::group_by("cyl") | dm::summarise(dm::agg::mean("mpg"));
/// @endcode
dstruct::DataFrame mtcars();

/// @brief Daily New York air quality, May to September 1973, identical to R's
///        `datasets::airquality`.
///
/// 153 rows and 6 numeric columns: `Ozone` (ppb), `Solar.R` (langleys), `Wind` (mph), `Temp`
/// (degrees F), `Month` (5-9) and `Day`. Missing values: `Ozone` 37, `Solar.R` 7.
///
/// @return A new 153 x 6 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto air = dm::datasets::airquality();
/// const auto complete = air.drop_nulls();   // 111 rows
/// @endcode
dstruct::DataFrame airquality();

/// @brief The Wisconsin diagnostic breast cancer data, as in scikit-learn's
///        `load_breast_cancer()`.
///
/// 569 rows and 31 columns: 30 numeric features of cell nuclei -- the mean, standard error and
/// "worst" value of radius, texture, perimeter, area, smoothness, compactness, concavity,
/// concave points, symmetry and fractal dimension (named like `mean_radius`,
/// `radius_error`, `worst_radius`) -- then `diagnosis`, a string "malignant" (212) or
/// "benign" (357). No missing values. A standard binary-classification benchmark.
///
/// @return A new 569 x 31 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto cancer = dm::datasets::breast_cancer();
/// std::print("{}\n", cancer.select({"mean_radius", "mean_texture", "diagnosis"}).head(5));
/// @endcode
/// @see wine()
dstruct::DataFrame breast_cancer();

/// @brief Efron et al.'s (2004) diabetes progression data, as in scikit-learn's
///        `load_diabetes(scaled = false)`.
///
/// 442 rows and 11 numeric columns: `age`, `sex` (1 or 2), `bmi`, `bp` (mean blood pressure),
/// six blood serum measurements `s1`..`s6`, and `progression`, a measure of disease progression
/// one year after baseline. Values are unscaled. No missing values. A standard regression
/// benchmark (the one used to introduce LARS).
///
/// @return A new 442 x 11 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto diabetes = dm::datasets::diabetes();
/// const auto& y = diabetes.get_column("progression").values();
/// @endcode
dstruct::DataFrame diabetes();

/// @brief 1797 8x8 images of handwritten digits, as in scikit-learn's `load_digits()`.
///
/// 1797 rows and 65 numeric columns: `pixel_0`..`pixel_63`, the 8x8 image in row-major order
/// with intensities 0..16, then `digit` (0-9). No missing values. Small enough to keep in
/// memory; see ImageLoader for the full 28x28 MNIST.
///
/// @return A new 1797 x 65 DataFrame owned by the caller.
///
/// @par Example
/// @code
/// const auto digits = dm::datasets::digits();
/// std::print("{}\n", digits.nrows());   // 1797
/// @endcode
/// @see ImageLoader
dstruct::DataFrame digits();

/// @brief ggplot2's diamonds data: prices and attributes of 53940 round-cut diamonds.
///
/// Downloaded on first use (2.7 MB) and cached; see fetch(). 53940 rows and 10 columns:
/// `carat`, `cut` ("Fair", "Good", "Very Good", "Premium", "Ideal"), `color` ("D" best to "J"),
/// `clarity` ("I1", "SI2", "SI1", "VS2", "VS1", "VVS2", "VVS1", "IF"), `depth`, `table`,
/// `price` (US dollars), and the dimensions `x`, `y`, `z` (mm). `cut`, `color` and `clarity`
/// are strings, the rest numeric. No missing values.
///
/// @return A new 53940 x 10 DataFrame owned by the caller.
/// @throws std::runtime_error if the file is not cached and cannot be downloaded.
///
/// @par Example
/// @code
/// const auto diamonds = dm::datasets::diamonds();
/// const auto by_cut = diamonds | dm::group_by("cut") | dm::summarise(dm::agg::mean("price"));
/// @endcode
/// @see fetch(), CsvReader
dstruct::DataFrame diamonds();

/// @brief California housing: the 1990 census, one row per block group (Pace and Barry 1997),
///        in the version with `ocean_proximity` popularized by Géron's *Hands-On ML*.
///
/// Downloaded on first use (1.4 MB) and cached; see fetch(). 20640 rows and 10 columns:
/// `longitude`, `latitude`, `housing_median_age`, `total_rooms`, `total_bedrooms`,
/// `population`, `households`, `median_income` (tens of thousands of dollars),
/// `median_house_value` (dollars) and `ocean_proximity` (string: "<1H OCEAN", "INLAND",
/// "ISLAND", "NEAR BAY", "NEAR OCEAN"). `total_bedrooms` has 207 missing values.
///
/// @return A new 20640 x 10 DataFrame owned by the caller.
/// @throws std::runtime_error if the file is not cached and cannot be downloaded.
///
/// @par Example
/// @code
/// const auto housing = dm::datasets::california_housing();
/// std::print("{}\n", dm::info(housing));
/// @endcode
/// @see fetch()
dstruct::DataFrame california_housing();

/// @brief 156 Sudoku puzzles from Peter Norvig's essay "Solving Every Sudoku Puzzle", in three
///        collections of increasing difficulty.
///
/// Downloaded on first use (14 KB) and cached; see fetch(). 156 rows and 4 columns:
/// `collection` -- string: "easy50" (50 grids from Project Euler problem 96), "top95" (95 hard
/// grids collected by Norvig) or "hardest" (11 grids posted as the hardest known); `id` -- the
/// puzzle's 1-based position in its collection; `puzzle` -- string of 81 characters read row
/// by row, `1`-`9` for a given digit and `.` for a blank; `givens` -- the number of given digits.
/// Use algorithms::sudoku to propagate, solve and draw them.
///
/// @return A new 156 x 4 DataFrame owned by the caller.
/// @throws std::runtime_error if the files are not cached and cannot be downloaded, or a file
///         does not hold the expected number of puzzles.
///
/// @par Example
/// @code
/// const auto puzzles = dm::datasets::sudoku();
/// const auto r = dm::algorithms::sudoku::propagate(puzzles.string_at("puzzle", 0));
/// @endcode
/// @see algorithms::sudoku::propagate()
dstruct::DataFrame sudoku();

/// @brief Any table-shaped dataset by name: "air_passengers", "airquality", "breast_cancer",
///        "california_housing", "diabetes", "diamonds", "digits", "eight_schools", "faithful",
///        "iris", "mtcars", "orthodont", "penguins", "sudoku", "titanic", "tooth_growth", "volcano"
///        or "wine".
///
/// The image datasets are not tables; open them with ImageLoader instead.
///
/// @param name A dataset name as listed in catalog().
/// @return A new DataFrame, as the dataset's own function returns it.
/// @throws std::invalid_argument for an unknown name, or an image dataset's name.
/// @throws std::runtime_error if a downloaded dataset cannot be fetched.
///
/// @par Example
/// @code
/// for (const auto& name : {"iris", "wine", "faithful"})
///   std::print("{}: {} rows\n", name, dm::datasets::load(name).nrows());
/// @endcode
/// @see catalog()
dstruct::DataFrame load(const std::string& name);

/// @brief A table describing every dataset available here, one row each, sorted by name.
///
/// Columns: `name`; `rows` and `columns` (for image datasets: train + test images, and
/// pixels per image); `storage` -- "built-in", "download" (fetched once, then loaded into
/// memory) or "stream" (read in batches by ImageLoader); `size_mb`, the approximate download
/// size (0 for built-in data); and a one-line `description`. Building it needs no files.
///
/// @return A new DataFrame owned by the caller.
///
/// @par Example
/// @code
/// std::print("{}\n", dm::datasets::catalog());
/// @endcode
/// @see load(), ImageLoader
dstruct::DataFrame catalog();

/// @brief An ImageBatch as a DataFrame: one row per image, columns `pixel_0`.. (each image's
///        values in the batch's layout order) followed by `label` and `index`.
///
/// Useful for running the table-oriented tools (summaries, PCA, plotting) on a sample of
/// images. All columns are numeric.
///
/// @param batch A batch from ImageLoader.
/// @return A new size() x (features() + 2) DataFrame.
///
/// @par Example
/// @code
/// dm::datasets::ImageLoader mnist("mnist", "test");
/// const auto frame = dm::datasets::to_dataframe(mnist.set_batch_size(500).next());   // 500 x 786
/// @endcode
/// @see ImageLoader, digits()
dstruct::DataFrame to_dataframe(const ImageBatch& batch);

} // namespace datamunge::datasets
