#pragma once
/// @file diffie_hellman.hpp
/// @brief Educational uint64 Diffie–Hellman arithmetic, exchanges and bounded prime-field cycles.
/// Agreement is an algebraic identity, not a security certificate. The legacy
/// exponentiation wrappers do not validate primes, generators, peers or exponents;
/// no randomness, authentication, KDF or constant-time primitive is supplied.
#include <datamunge/algorithms/modular_exponentiation.hpp>
#include <cstddef>
#include <cstdint>
#include <vector>
namespace datamunge::algorithms {
/// @brief Public values and raw shared residues from one deterministic toy exchange.
/// Retains supplied g/p and four computed residues, not private exponents. Does
/// not certify a group or protocol. No shared state; raw residues are exposed.
/// @par Example
/// @code
/// const auto x=dm::algorithms::dh_exchange(5,6,15,23);
/// std::print("{} {} {} {}\n",x.alice_public,x.bob_public,x.alice_shared,x.bob_shared); // 8 19 2 2
/// @endcode
/// @see dh_exchange(), dh_public_key(), dh_shared_secret()
struct DhExchange {
 std::uint64_t generator{0}; ///< Original supplied base, unreduced.
 std::uint64_t modulus{0}; ///< Original nonzero modulus in a native result.
 std::uint64_t alice_public{0}; ///< g^alice_secret modulo p.
 std::uint64_t bob_public{0}; ///< g^bob_secret modulo p.
 std::uint64_t alice_shared{0}; ///< bob_public^alice_secret modulo p.
 std::uint64_t bob_shared{0}; ///< alice_public^bob_secret modulo p.
};
/// @brief Complete cyclic subgroup generated by a validated nonzero prime-field element.
/// values[x]=g^x mod p for x=0..order-1, starting at1. The next product closes
/// back to1; exactly order products are performed. Values are distinct, owned and
/// ordered by exponent. This small-cycle enumeration is not a strength estimate.
/// @par Example
/// @code
/// const auto c=dm::algorithms::dh_power_cycle(4,23);
/// std::print("{} {}\n",c.order,c.values); // 11 [1, 4, 16, 18, 3, 12, 2, 8, 9, 13, 6]
/// @endcode
/// @see dh_power_cycle()
struct DhPowerCycle {
 std::uint64_t modulus{0}; ///< Validated prime p>=2 in a native result.
 std::uint64_t generator{0}; ///< Original element in [1,p), not necessarily a full generator.
 std::uint64_t order{0}; ///< Exact element order and actual closing-product count.
 std::vector<std::uint64_t> values; ///< Distinct generated residues, including initial identity.
};
/// @brief Compute g^secret modulo p, preserving the original arithmetic-only API.
/// Delegates to exact mod_pow(); p may be prime, composite or one. Exponent zero,
/// zero/nonunit bases and unreduced g are accepted. Does not sample/validate keys,
/// groups or public values. Variable work exposes exponent properties.
/// @param g Arbitrary unsigned base.
/// @param secret Unsigned exponent, including zero.
/// @param p Nonzero modulus; not validated as a prime field.
/// @return Exact public residue in [0,p); zero when p=1.
/// @throws std::invalid_argument If p is zero.
/// @par Example
/// @code
/// std::print("{}\n",dm::algorithms::dh_public_key(5,6,23)); // 8
/// @endcode
/// @par References
/// - W. Diffie and M. E. Hellman (1976), New Directions in Cryptography, IEEE IT22(6), 644–654, doi:10.1109/TIT.1976.1055638. This is only the fixed-width arithmetic operation.
/// @see dh_shared_secret(), dh_exchange(), mod_pow()
std::uint64_t dh_public_key(std::uint64_t g,std::uint64_t secret,std::uint64_t p);
/// @brief Compute peer_public^secret modulo p without protocol or peer validation.
/// Same exact arithmetic/edge conventions as dh_public_key(). Zero/one/p-1 peers
/// are accepted and can collapse the output; callers must not infer safe agreement
/// from matching residues. No authentication, key derivation or constant-time work.
/// @param peer_public Arbitrary unsigned received base; reduced by modular powering.
/// @param secret Unsigned exponent, including zero.
/// @param p Nonzero modulus; no primality/group check.
/// @return Exact raw shared residue, not a derived symmetric key.
/// @throws std::invalid_argument If p is zero.
/// @par Example
/// @code
/// std::print("{}\n",dm::algorithms::dh_shared_secret(19,6,23)); // 2
/// @endcode
/// @par References
/// - W. Diffie and M. E. Hellman (1976), New Directions in Cryptography, doi:10.1109/TIT.1976.1055638.
/// @see dh_public_key(), dh_exchange()
std::uint64_t dh_shared_secret(std::uint64_t peer_public,std::uint64_t secret,std::uint64_t p);
/// @brief Execute four arithmetic exponentiations and retain both parties' raw results.
/// Deterministic toy transcript; private exponents are inputs but are not stored.
/// Preserves all legacy arithmetic conventions, including p=1 and zero exponents.
/// Agreement holds algebraically and does not prove secrecy, primality, subgroup
/// strength or peer identity. O(log(a)+log(b)+1) word operations, O(1) storage;
/// all operations are variable-time and no randomness/KDF is performed.
/// @param g Arbitrary unsigned base, retained unreduced.
/// @param alice_secret Alice's unsigned exponent.
/// @param bob_secret Bob's unsigned exponent.
/// @param p Nonzero prime or composite modulus.
/// @return Public values and the two exact raw shared residues.
/// @throws std::invalid_argument If p is zero.
/// @par Example
/// @code
/// const auto x=dm::algorithms::dh_exchange(7,123456,987654,2147483647);
/// std::print("{} {} {}\n",x.alice_public,x.bob_public,x.alice_shared); // 744111946 1598667707 490982923
/// @endcode
/// @par References
/// - W. Diffie and M. E. Hellman (1976), New Directions in Cryptography, doi:10.1109/TIT.1976.1055638.
/// @see dh_public_key(), dh_shared_secret(), DhExchange
DhExchange dh_exchange(std::uint64_t g,std::uint64_t alice_secret,std::uint64_t bob_secret,std::uint64_t p);
/// @brief Enumerate an exact generated subgroup until the first return to the identity.
/// Checks p>=2 prime with the existing deterministic uint64 primality API and
/// 1<=g<p before any cap/enumeration. Performs one product per emitted residue,
/// including the closing product; order divides p-1. The cap is online because
/// order is unknown. Failure returns no partial cycle. O(order) storage/work plus
/// the primality check. Not suitable for enumerating large production groups.
/// @param g Nonzero canonical field element in [1,p), including identity1.
/// @param p Prime modulus, including p=2.
/// @param max_order Actual residue/product cap, default1000000; zero disables only this cap.
/// @return Owned distinct powers, exact order and original parameters.
/// @throws std::invalid_argument If p is not prime or g is out of range, before cap checks.
/// @throws std::length_error For the online order cap or vector capacity.
/// @throws std::bad_alloc For allocation failure.
/// @par Example
/// @code
/// const auto c=dm::algorithms::dh_power_cycle(5,23,22);
/// std::print("{} {} {}\n",c.order,c.values.front(),c.values.back()); // 22 1 14
/// @endcode
/// @par References
/// - W. Diffie and M. E. Hellman (1976), New Directions in Cryptography, doi:10.1109/TIT.1976.1055638 (powers in a finite multiplicative group).
/// @see dh_exchange(), is_probable_prime(), DhPowerCycle
DhPowerCycle dh_power_cycle(std::uint64_t g,std::uint64_t p,std::size_t max_order=1000000);
} // namespace datamunge::algorithms
