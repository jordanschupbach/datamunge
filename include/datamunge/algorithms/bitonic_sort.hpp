#pragma once
/// @file bitonic_sort.hpp
/// @brief One canonical arbitrary-length bitonic network for sorting, inspection and tracing.
#include <algorithm>
#include <cstddef>
#include <utility>
#include <vector>

namespace datamunge::algorithms {
/// @brief A fixed compare/exchange connection between two network wires.
/// first<second. Ascending sends the smaller value to first; descending sends it
/// to second. Stages are zero-based dependency layers with disjoint wire pairs.
/// @par Example
/// @code
/// const auto network=dm::algorithms::bitonic_network(4);
/// std::print("{} {}\n",network.comparators[0].first,network.comparators[0].second); // 0 1
/// @endcode
/// @see BitonicNetwork
struct BitonicComparator {
  std::size_t first{0}; ///< First wire, always the smaller index.
  std::size_t second{0}; ///< Second wire.
  bool ascending{true}; ///< Whether first receives the smaller value.
  std::size_t stage{0}; ///< Zero-based parallel dependency layer.
};

/// @brief Owned, value-independent topology generated by the canonical bitonic visitor.
/// Comparators are grouped in nondecreasing stage order. Empty/singleton inputs
/// need no comparators or stages. Construction stores O(n log^2(n+1)) entries.
/// @par Example
/// @code
/// const auto network=dm::algorithms::bitonic_network(4);
/// std::print("{} {}\n",network.comparators.size(),network.stages); // 6 3
/// @endcode
/// @see bitonic_network(), bitonic_sort()
struct BitonicNetwork {
  std::size_t wires{0}; ///< Input/output length, including zero.
  std::size_t stages{0}; ///< Number of dependency layers in this construction.
  std::vector<BitonicComparator> comparators; ///< Every comparison, grouped by stage.
};

/// @brief Actual values and swap decision at one canonical integer comparator.
/// The trace follows sequential recursive execution; stage numbers can decrease
/// between independent subproblems. Topology is fixed even when swaps differ.
/// @par Example
/// @code
/// const auto trace=dm::algorithms::bitonic_sort_trace({2,1});
/// std::print("{} {}\n",trace.steps[0].first_before,trace.steps[0].first_after); // 2 1
/// @endcode
/// @see BitonicTrace
struct BitonicStep {
  BitonicComparator comparator; ///< Wires, direction and dependency stage.
  int first_before{0}; ///< First wire value before the comparison.
  int second_before{0}; ///< Second wire value before the comparison.
  int first_after{0}; ///< First wire value after the comparison.
  int second_after{0}; ///< Second wire value after the comparison.
  bool swapped{false}; ///< Whether the implementation exchanged the values.
};

/// @brief Owned input/output and chronological integer compare/exchange events.
/// The unrecorded sorter does not allocate these records. Recording uses
/// O(n log^2(n+1)) storage plus the owned input/output vectors.
/// @par Example
/// @code
/// const auto trace=dm::algorithms::bitonic_sort_trace({3,1,4,2});
/// std::print("{}\n",trace.output); // [1, 2, 3, 4]
/// @endcode
/// @see bitonic_sort_trace(), bitonic_network()
struct BitonicTrace {
  std::vector<int> input; ///< Original sequence.
  std::vector<int> output; ///< Sorted ascending sequence.
  std::vector<BitonicStep> steps; ///< Canonical sequential comparison order.
  std::size_t stages{0}; ///< Parallel dependency depth of the topology.
};

/// @brief Internal allocation-free traversal and application of the network topology.
namespace detail {
/// @brief Emit a general-length bitonic merge and label its dependency layers.
/// @tparam Emit Callable receiving first,second,ascending,stage.
/// @param lo First wire of the subrange.
/// @param n Number of wires, within the caller's addressable range.
/// @param ascending Requested merge direction.
/// @param stage First available dependency layer.
/// @param emit Borrowed comparator consumer.
/// @return First free layer after this merge.
template<class Emit>
std::size_t bitonic_merge_visit(std::size_t lo,std::size_t n,bool ascending,
                                std::size_t stage,Emit& emit) {
  if (n<=1) return stage;
  std::size_t stride=1;
  while (stride<=(n-1)/2) stride*=2;
  for (std::size_t i=0;i<n-stride;++i) emit(lo+i,lo+i+stride,ascending,stage);
  const auto left=bitonic_merge_visit(lo,stride,ascending,stage+1,emit);
  const auto right=bitonic_merge_visit(lo+stride,n-stride,ascending,stage+1,emit);
  return std::max(left,right);
}

/// @brief Emit recursive opposing sorts followed by their bitonic merge.
/// @tparam Emit Callable receiving a comparator's wires, direction and stage.
/// @param lo First wire.
/// @param n Subrange size.
/// @param ascending Final direction.
/// @param stage First available dependency layer.
/// @param emit Borrowed consumer.
/// @return First free layer after sorting this subrange.
template<class Emit>
std::size_t bitonic_sort_visit(std::size_t lo,std::size_t n,bool ascending,
                               std::size_t stage,Emit& emit) {
  if (n<=1) return stage;
  const auto half=n/2;
  const auto left=bitonic_sort_visit(lo,half,!ascending,stage,emit);
  const auto right=bitonic_sort_visit(lo+half,n-half,ascending,stage,emit);
  return bitonic_merge_visit(lo,n,ascending,std::max(left,right),emit);
}

/// @brief Apply canonical comparisons and report post-comparison values to an observer.
/// @tparam T Swappable element with a consistent greater-than ordering.
/// @tparam Observe Callable taking comparator,swapped,first_after,second_after.
/// @param values Mutable sequence.
/// @param observe Post-comparison consumer; may throw with partial mutation.
/// @return Dependency depth; no network storage is allocated here.
template<class T,class Observe>
std::size_t bitonic_apply(std::vector<T>& values,Observe observe) {
  /// @brief Compare/exchange in the historical direction convention, then observe the result.
  /// @param first First wire.
  /// @param second Second wire.
  /// @param ascending Whether the smaller value belongs at first.
  /// @param stage Dependency layer.
  auto compare=[&](std::size_t first,std::size_t second,bool ascending,std::size_t stage) {
    const bool swapped=ascending==(values[first]>values[second]);
    if (swapped) std::swap(values[first],values[second]);
    observe(BitonicComparator{first,second,ascending,stage},swapped,values[first],values[second]);
  };
  return bitonic_sort_visit(0,values.size(),true,0,compare);
}
} // namespace detail

/// @brief Sort any vector length in ascending order with a fixed bitonic network.
/// Comparisons follow the same topology as bitonic_network(), without allocating
/// a network or trace. The loop and swap branches remain ordinary C++ execution:
/// fixed wire accesses do not imply constant-time machine behavior. Not stable;
/// descending comparisons retain the historical exchange-on-equality convention.
/// O(n log^2(n+1)) comparisons and O(log(n+1)) recursion-stack storage. No shared
/// state; comparison/move exceptions propagate with possibly partially changed input.
/// @tparam T Swappable element whose greater-than operator defines a consistent ordering.
/// @param values Sequence to mutate, possibly empty or of non-power-of-two length.
/// @par Example
/// @code
/// std::vector<int> values{8,3,1,7,2};
/// dm::algorithms::bitonic_sort(values);
/// std::print("{}\n",values); // [1, 2, 3, 7, 8]
/// @endcode
/// @par References
/// - K. E. Batcher (1968), Sorting networks and their applications,
///   doi:10.1145/1468075.1468121 (this implementation generalises to arbitrary lengths).
/// - H. W. Lang, Bitonic sorting network for n not a power of 2,
///   https://hwlang.de/algorithmen/sortieren/bitonic/oddn.htm.
/// @see bitonic_network(), bitonic_sort_trace()
template<class T>
void bitonic_sort(std::vector<T>& values) {
  detail::bitonic_apply(values,[](BitonicComparator,bool,const T&,const T&){});
}

/// @brief Materialise the canonical value-independent bitonic comparator schedule.
/// Construction and output storage are O(n log^2(n+1)), using linear bucket
/// grouping by stage after emission. Every stage has disjoint wire pairs, so its
/// comparisons can run independently; this function does not launch workers.
/// No input data or mutable global state is used.
/// @param wires Number of sequence elements; zero and one give an empty network.
/// @return Owned comparators in nondecreasing stage order and the stage count.
/// @par Example
/// @code
/// const auto network=dm::algorithms::bitonic_network(8);
/// std::print("{} {}\n",network.comparators.size(),network.stages); // 24 6
/// @endcode
/// @par References
/// - K. E. Batcher (1968), Sorting networks and their applications,
///   doi:10.1145/1468075.1468121.
/// - H. W. Lang, arbitrary-length construction,
///   https://hwlang.de/algorithmen/sortieren/bitonic/oddn.htm.
/// @see bitonic_sort(), BitonicComparator
BitonicNetwork bitonic_network(std::size_t wires);

/// @brief Sort an owned integer sequence while recording the canonical comparator decisions.
/// Uses the same application loop as bitonic_sort(). Records values before and
/// after each comparison, including comparisons that cause no swap. O(n log^2(n+1))
/// time and recording storage; no caller input or shared state is mutated.
/// @param values Integer input, copied or moved into the result's owned vectors.
/// @return Original values, sorted values, chronological steps and dependency depth.
/// @par Example
/// @code
/// const auto trace=dm::algorithms::bitonic_sort_trace({3,1,4,2});
/// std::print("{} {}\n",trace.steps.size(),trace.stages); // 6 3
/// @endcode
/// @par References
/// - K. E. Batcher (1968), Sorting networks and their applications,
///   doi:10.1145/1468075.1468121.
/// - H. W. Lang, arbitrary-length construction,
///   https://hwlang.de/algorithmen/sortieren/bitonic/oddn.htm.
/// @see bitonic_sort(), bitonic_network()
BitonicTrace bitonic_sort_trace(std::vector<int> values);
} // namespace datamunge::algorithms
