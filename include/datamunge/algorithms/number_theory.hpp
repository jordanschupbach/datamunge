#pragma once

/// @file number_theory.hpp
/// @brief Binary GCD, Tonelli-Shanks square roots, Karatsuba multiplication, and Shanks's
///        baby-step giant-step discrete logarithm with its instrumented variant.

#include <cstdint>
#include <string>
#include <vector>

namespace datamunge::algorithms {

/// @brief The *binary GCD algorithm* (Stein, 1967) for the greatest common divisor of @p a and
///        @p b. Unlike the Euclidean algorithm it uses no division or modulo -- only subtraction and
///        bit shifts (both cheap in hardware) -- via three rules: @c gcd(a,b) removes common factors
///        of two, halves any even operand, and replaces the larger of two odds by their difference
///        (which is even). It runs in @c O(log(max(a,b))) arithmetic operations. By convention
///        @c gcd(0,0)=0 and @c gcd(x,0)=x.
///
/// @param a the first operand.
/// @param b the second operand.
/// @return the greatest common divisor of @p a and @p b.
std::uint64_t binary_gcd(std::uint64_t a, std::uint64_t b);

/// @brief The result of a modular square root: whether a root @ref exists, and if so one @ref root
///        @c r (the smaller of the two, @c r <= p-r) with @c r*r ≡ n (mod p).
struct ModSqrt {
    bool          exists{false}; ///< whether @c n is a quadratic residue modulo @c p.
    std::uint64_t root{0};       ///< a square root of @c n modulo @c p (the smaller one).
};

/// @brief The *Tonelli-Shanks algorithm*: computes a square root of @p n modulo an odd prime @p p,
///        i.e. an @c r with @c r*r ≡ n (mod p), or reports that none exists. It first tests
///        solvability by Euler's criterion (@c n^{(p-1)/2} ≡ 1), then, writing @c p-1 = Q·2^S with
///        @c Q odd, iteratively refines a candidate root using a fixed quadratic non-residue -- the
///        general method behind computing square roots in finite fields (used in elliptic-curve
///        point decompression and quadratic sieves). For @c p ≡ 3 (mod 4) it uses the direct
///        @c n^{(p+1)/4} shortcut. Expected @c O(log^2 p) time.
///
/// @param n the value whose square root is sought (taken modulo @p p).
/// @param p an odd prime modulus.
/// @return a @ref ModSqrt: @c exists is false when @p n is a non-residue; otherwise @c root*root ≡ n.
ModSqrt tonelli_shanks(std::uint64_t n, std::uint64_t p);

/// @brief *Karatsuba multiplication* (Karatsuba, 1960): multiplies two arbitrarily large
///        non-negative integers given as decimal strings, in @c O(n^{log_2 3}) ≈ @c O(n^{1.585})
///        time rather than the schoolbook @c O(n^2). It splits each number into high and low halves
///        and computes the product from only *three* half-size products (instead of four) via the
///        identity @c (x1·B+x0)(y1·B+y0) = z2·B^2 + z1·B + z0 with @c z1 = (x1+x0)(y1+y0) - z2 - z0.
///        The recursion falls back to schoolbook multiplication for small operands.
///
/// @param a the first factor as a non-negative decimal string (no sign; leading zeros allowed).
/// @param b the second factor as a non-negative decimal string.
/// @return the product as a decimal string with no leading zeros (\"0\" for a zero product).
std::string karatsuba_multiply(const std::string& a, const std::string& b);

/// @brief The result of a discrete-logarithm search: whether a solution @ref exists and, if so, an
///        @ref exponent @c x with @c base^x ≡ target (mod p).
struct DiscreteLog {
    bool          exists{false};  ///< whether the logarithm exists.
    std::uint64_t exponent{0};    ///< an @c x with @c base^x ≡ target (mod p).
};

/// @brief The *baby-step giant-step algorithm* (Shanks): solves the discrete logarithm
///        @c base^x ≡ target (mod p) for a prime modulus @p p, in @c O(sqrt(p)) time and space --
///        a meet-in-the-middle speedup over the @c O(p) brute-force search. Writing @c x = i·m + j
///        with @c m = ceil(sqrt(p-1)), it tabulates the "baby steps" @c base^j and then takes
///        "giant steps" of size @c m, looking each up in the table. It returns a valid exponent when
///        @p target lies in the subgroup generated by @p base, and reports failure otherwise.
///
/// @param base   the base of the logarithm (a residue modulo @p p).
/// @param target the value whose logarithm base @p base is sought.
/// @param p      a prime modulus.
/// @return a @ref DiscreteLog: @c exists is false when no such exponent exists; otherwise
///         @c base^exponent ≡ target (mod p).
DiscreteLog baby_step_giant_step(std::uint64_t base, std::uint64_t target, std::uint64_t p);

/// @brief A baby-step giant-step run with its operation counts and, optionally, the visited values.
struct BsgsTrace {
    bool          exists{false};      ///< whether a logarithm was found.
    std::uint64_t exponent{0};        ///< the smallest @c x in [0, order) with @c base^x ≡ target, when found.
    std::uint64_t order{0};           ///< the group order @c n used to size the search.
    std::uint64_t table_size{0};      ///< @c m, the number of baby steps tabulated.
    std::uint64_t baby_steps{0};      ///< multiplications spent building the table (equals @c m).
    std::uint64_t giant_steps{0};     ///< table lookups made before the match (or before giving up).
    std::uint64_t giant_index{0};     ///< @c i of the match @c x = i·m + j.
    std::uint64_t baby_index{0};      ///< @c j of the match.
    std::vector<std::uint64_t> baby;  ///< @c base^j for j < m, when recording was requested.
    std::vector<std::uint64_t> giant; ///< @c target·base^{-mi} for each giant step taken, when recorded.
};

/// @brief Baby-step giant-step with a chosen group order and table size, counting its work.
///
/// Solves @c base^x ≡ target (mod p) for @c x in [0, n), where n is @p order (default @c p-1). With
/// @c m baby steps it needs at most @c ceil(n/m) giant steps, so @c m = ceil(sqrt(n)) minimises the
/// worst case @c m + n/m. Passing the exact order of @p base (a divisor of @c p-1) shrinks the search.
///
/// @param base       the base, a unit modulo @p p.
/// @param target     the value whose logarithm is sought.
/// @param p          a prime modulus.
/// @param order      a multiple of the order of @p base (0 means @c p-1).
/// @param table_size the number of baby steps @c m (0 means @c ceil(sqrt(order))).
/// @param record     whether to store the baby and giant values in the result.
/// @return the trace; @c exists is false when @p target is not a power of @p base.
/// @throws std::invalid_argument if @p p < 2 or @p base is not coprime to @p p.
BsgsTrace baby_step_giant_step_trace(std::uint64_t base, std::uint64_t target, std::uint64_t p,
                                     std::uint64_t order = 0, std::uint64_t table_size = 0,
                                     bool record = false);

/// @brief The multiplicative order of @p g modulo the prime @p p: the least @c k > 0 with
///        @c g^k ≡ 1. It divides @c p-1, so it is found by factoring @c p-1 and dividing out
///        each prime while the power stays 1.
/// @throws std::invalid_argument if @p p < 2 or @p g ≡ 0 (mod p).
std::uint64_t element_order(std::uint64_t g, std::uint64_t p);

/// @brief The smallest primitive root modulo the prime @p p (a generator of the whole group).
/// @throws std::invalid_argument if @p p < 2.
std::uint64_t primitive_root(std::uint64_t p);

} // namespace datamunge::algorithms
